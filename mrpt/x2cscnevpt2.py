r"""Dense no-Kramers X2C strongly-contracted NEVPT2.

The spin-orbital Hamiltonian used by this module is

.. math::

   H = \sum_{pq} h_{pq} C_p D_q
       + \frac12 \sum_{pqrs} w_{pqrs} C_p C_q D_s D_r,

with unantisymmetrized integrals

.. math::

   w_{pqrs} = \mathrm{eri}_{prqs}, \qquad
   \mathrm{eri}_{pqrs} = (pq|rs).

All indices label individual complex spinors.  There is no implicit spin
summation, Kramers compression, ``E1/E2`` spin-free operator, or spatial
``gamma`` factor.  An explicit ``strong_contraction_groups`` label vector can
nevertheless request that symmetry-partner core/external channels be summed
before their strongly-contracted denominator is formed.  This recovers, for
example, the spin-free scalar limit without guessing partners from accidental
orbital-energy degeneracies.  The eight strongly-contracted spaces follow
Sections I.E--I.L of the Supporting Information to Shiozaki and Mizukami,
JCTC 2015:

``ijrs`` (E, Eqs. 13--14), ``ijr`` (F, Eqs. 15--17), ``ij`` (G,
Eqs. 18--20), ``rsi`` (H, Eqs. 21--23), ``ir`` (I, Eqs. 24--27), ``i``
(J, Eqs. 28--30), ``rs`` (K, Eqs. 31--33), and ``r`` (L, Eqs. 34--36).

The actual norm and Dyall-commutator contractions are generated by the
installed Block2 Wick bindings.  Active expectation values are lowered to
raw SGF particle RDMs with axes

``dm_k[p1,...,pk,qk,...,q1] = <C[p1]...C[pk]D[qk]...D[q1]>``.

The default ``strict_si`` denominator is the one-sided expression printed in
the SI.  Finite imaginary residuals and related tolerance failures emit
``MRPTNumericalWarning`` before the selected value is converted to real
arithmetic.  Non-finite values and non-positive or near-zero denominators
remain hard errors.  The independently generated left branch is always
checked against the adjoint of the right branch.  An explicit
``hermitianized`` mode retains the manifestly Hermitian half-sum as a
finite-MPS stabilization, but records whether the one-sided SI gate failed;
it is therefore never silently presented as the literal SI expression.
"""

