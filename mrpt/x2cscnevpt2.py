@lru_cache(maxsize=1)
def _compile_wick_equations() -> _WickEquationBundle:
    types = _block2_wick_types()
    parse, parse_tensor = _wick_parsers(types)

    h_dyall_active = parse("SUM <ab> h[ab] C[a] D[b]")
    h_dyall_active += parse(
        "0.5 SUM <abcd> w[abcd] C[a] C[b] D[d] D[c]"
    )

    norm_code = {}
    transition_norm_code = {}
    right_commutator_code = {}
    left_commutator_code = {}
    commutator_code = {}
    norm_text = {}
    transition_norm_text = {}
    right_commutator_text = {}
    left_commutator_text = {}
    commutator_text = {}
    for key in SUBSPACE_ORDER:
        ket = parse(_PERTURBER_EXPRESSIONS[key])
        bra = _conjugate_with_coefficients(ket, types)

        reduced_norm = _vacuum_reduce(bra * ket)
        norm = _lower_active_operators(reduced_norm, types)
        transition_norm = _lower_active_operators(
            reduced_norm, types, include_overlap=True
        )

        # [one-/two-body H_D, at-most-two-body T] is connected and contains
        # at most three creation and three destruction operators.  Asking
        # Wick for max_unctr=6 discards only the zero-contraction H2*T2
        # products, which cancel identically in the commutator.  This ordering
        # is important when w has intentionally been given no permutation
        # rules: otherwise Block2 cannot graph-canonicalize two dummy-index
        # forms of that exact zero before the bra is multiplied, producing a
        # spurious 5-RDM in the r/i classes.
        connected_right = (h_dyall_active ^ ket).expand(6).simplify()
        right_commutator = _lower_active_operators(
            _vacuum_reduce(bra * connected_right), types
        )
        connected_left = (bra ^ h_dyall_active).expand(6).simplify()
        left_commutator = _lower_active_operators(
            _vacuum_reduce(connected_left * ket), types
        )

        # The SI one-sided commutator is real when the CAS reference is an
        # exact eigenstate of the active Dyall Hamiltonian.  A converged DMRG
        # MPS has a finite eigen-equation residual, however, so that
        # one-sided form need not itself be Hermitian.  Form its Hermitian
        # part explicitly at the operator/Wick level:
        #
        #   1/2 { T^dagger [H_D,T] + [T^dagger,H_D] T }.
        #
        # This is exactly the SI expression in the eigenstate limit, remains
        # connected and requires no RDM above rank four.  The independently
        # generated left and right branches are retained so execution can
        # verify their adjoint relation; this is deliberately not a final
        # ``.real`` projection of the one-sided numerical result.
        commutator = (0.5 * (right_commutator + left_commutator)).simplify()

        norm_target = parse_tensor(f"norm[{key}]")
        commutator_target = parse_tensor(f"commutator[{key}]")
        norm_code[key] = norm.to_einsum(norm_target)
        transition_norm_code[key] = transition_norm.to_einsum(norm_target)
        right_commutator_code[key] = right_commutator.to_einsum(
            commutator_target
        )
        left_commutator_code[key] = left_commutator.to_einsum(
            commutator_target
        )
        commutator_code[key] = commutator.to_einsum(commutator_target)
        norm_text[key] = repr(norm)
        transition_norm_text[key] = repr(transition_norm)
        right_commutator_text[key] = repr(right_commutator)
        left_commutator_text[key] = repr(left_commutator)
        commutator_text[key] = repr(commutator)

    return _WickEquationBundle(
        norm_code=norm_code,
        transition_norm_code=transition_norm_code,
        right_commutator_code=right_commutator_code,
        left_commutator_code=left_commutator_code,
        commutator_code=commutator_code,
        norm_text=norm_text,
        transition_norm_text=transition_norm_text,
        right_commutator_text=right_commutator_text,
        left_commutator_text=left_commutator_text,
        commutator_text=commutator_text,
    )


def dump_wick_equations(filename: str | None = None) -> str:
    """Return (and optionally write) auditable equations for all eight spaces."""

    equations = _compile_wick_equations()
    sections = []
    for key in SUBSPACE_ORDER:
        sections.extend(
            (
                f"[{key}] perturber\n{_PERTURBER_EXPRESSIONS[key]}",
                f"[{key}] norm expression\n{equations.norm_text[key]}",
                f"[{key}] norm einsum\n{equations.norm_code[key]}",
                f"[{key}] transition norm expression\n"
                f"{equations.transition_norm_text[key]}",
                f"[{key}] transition norm einsum\n"
                f"{equations.transition_norm_code[key]}",
                f"[{key}] right Dyall commutator expression\n"
                f"{equations.right_commutator_text[key]}",
                f"[{key}] right Dyall commutator einsum\n"
                f"{equations.right_commutator_code[key]}",
                f"[{key}] left Dyall commutator expression\n"
                f"{equations.left_commutator_text[key]}",
                f"[{key}] left Dyall commutator einsum\n"
                f"{equations.left_commutator_code[key]}",
                f"[{key}] Hermitian Dyall commutator expression\n"
                f"{equations.commutator_text[key]}",
                f"[{key}] Hermitian Dyall commutator einsum\n"
                f"{equations.commutator_code[key]}",
            )
        )
    text = "\n\n".join(sections) + "\n"
    if filename is not None:
        with open(filename, "w", encoding="utf-8") as handle:
            handle.write(text)
    return text


