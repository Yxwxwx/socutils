def _block2_wick_types():
    try:
        from block2 import (
            MapPStrIntVectorWickPermutation,
            MapWickIndexTypesSet,
            VectorWickIndex,
            VectorWickString,
            VectorWickTensor,
            WickExpr,
            WickIndex,
            WickIndexTypes,
            WickString,
            WickTensor,
            WickTensorTypes,
        )
    except ImportError as error:  # pragma: no cover - installation error
        raise RuntimeError(
            "block2 must be installed with the internal-contraction Wick bindings"
        ) from error
    return {
        "MapPStrIntVectorWickPermutation": MapPStrIntVectorWickPermutation,
        "MapWickIndexTypesSet": MapWickIndexTypesSet,
        "VectorWickIndex": VectorWickIndex,
        "VectorWickString": VectorWickString,
        "VectorWickTensor": VectorWickTensor,
        "WickExpr": WickExpr,
        "WickIndex": WickIndex,
        "WickIndexTypes": WickIndexTypes,
        "WickString": WickString,
        "WickTensor": WickTensor,
        "WickTensorTypes": WickTensorTypes,
    }


def _wick_parsers(types):
    index_types = types["WickIndexTypes"]
    index = types["WickIndex"]
    index_map = types["MapWickIndexTypesSet"]()
    index_map[index_types.Inactive] = index.parse_set("ijklmnoz")
    index_map[index_types.Active] = index.parse_set("abcdefghpq")
    index_map[index_types.External] = index.parse_set("rstuvwxy")

    # Deliberately empty.  qc_phys/qc_chem contain ordinary permutations that
    # are false for general complex spinors when the required conjugation is
    # omitted.  Hermitian ERI identities are numerical checks, not Wick rules.
    permutation_map = types["MapPStrIntVectorWickPermutation"]()
    parse = lambda expression: types["WickExpr"].parse(
        expression, index_map, permutation_map
    )
    parse_tensor = lambda expression: types["WickTensor"].parse(
        expression, index_map, permutation_map
    )
    return parse, parse_tensor


def _conjugate_with_coefficients(expression, types):
    """Hermitian-conjugate operators and explicitly rename coefficient data.

    Block2 0.5.4rc16 reverses/adjoints C/D in ``WickExpr.conjugate()`` but
    intentionally does not conjugate ordinary coefficient tensors.  The
    renamed ``hc`` and ``wc`` arrays are bound to elementwise conjugates at
    execution time.
    """

    tensor_type = types["WickTensorTypes"]
    result = expression.conjugate()
    names = {"h": "hc", "w": "wc"}
    for term in result.terms:
        for tensor in term.tensors:
            if tensor.type == tensor_type.Tensor and tensor.name in names:
                tensor.name = names[tensor.name]
    return result


def _vacuum_reduce(expression):
    """Contract the external vacuum and filled inactive determinant."""

    return (
        expression.expand()
        .remove_external()
        .remove_inactive()
        .simplify()
    )


def _lower_active_operators(expression, types, *, include_overlap=False):
    """Lower active strings to raw RDMs, optionally including rank zero.

    Ordinary expectation values may leave an active-space identity implicit.
    A transition matrix element may not: its rank-zero density is the model
    state overlap.  ``include_overlap`` therefore appends an explicit scalar
    ``dm0[]`` tensor to every term without active creation/destruction
    operators.
    """

    tensor_type = types["WickTensorTypes"]
    vector_index = types["VectorWickIndex"]
    vector_string = types["VectorWickString"]
    vector_tensor = types["VectorWickTensor"]
    wick_expr = types["WickExpr"]
    wick_string = types["WickString"]
    wick_tensor = types["WickTensor"]

    lowered_terms = vector_string()
    for term in expression.terms:
        coefficients = vector_tensor()
        operators = []
        for tensor in term.tensors:
            if tensor.type in (
                tensor_type.CreationOperator,
                tensor_type.DestroyOperator,
            ):
                operators.append(tensor)
            else:
                coefficients.append(tensor)

        if operators:
            kinds = [tensor.type for tensor in operators]
            ncreation = kinds.count(tensor_type.CreationOperator)
            ndestroy = kinds.count(tensor_type.DestroyOperator)
            expected = [tensor_type.CreationOperator] * ncreation
            expected += [tensor_type.DestroyOperator] * ndestroy
            if ncreation != ndestroy or kinds != expected:
                raise RuntimeError(
                    "Wick left an active operator string that is not a "
                    f"particle RDM: {term!r}"
                )
            if ncreation > 4:
                raise RuntimeError(
                    "SC-NEVPT2 Wick expansion requested an active "
                    f"{ncreation}-RDM; recheck the commutator: {term!r}"
                )
            indices = vector_index()
            for tensor in operators:
                indices.append(tensor.indices[0])
            coefficients.append(wick_tensor(f"dm{ncreation}", indices))
        elif include_overlap:
            coefficients.append(wick_tensor("dm0", vector_index()))

        lowered_terms.append(
            wick_string(coefficients, term.ctr_indices, term.factor)
        )
    return wick_expr(lowered_terms).simplify()


@lru_cache(maxsize=1)
def _compile_wick_equations() -> _WickEquationBundle:
    types = _block2_wick_types()
    parse, parse_tensor = _wick_parsers(types)

    h_dyall_active = parse("SUM <ab> h[ab] C[a] D[b]")
    h_dyall_active += parse(
        "0.5 SUM <abcd> w[abcd] C[a] C[b] D[d] D[c]"
    )

    norm_code = {}
    transition_norm_code = {}
    right_commutator_code = {}
    left_commutator_code = {}
    commutator_code = {}
    norm_text = {}
    transition_norm_text = {}
    right_commutator_text = {}
    left_commutator_text = {}
    commutator_text = {}
    for key in SUBSPACE_ORDER:
        ket = parse(_PERTURBER_EXPRESSIONS[key])
        bra = _conjugate_with_coefficients(ket, types)

        reduced_norm = _vacuum_reduce(bra * ket)
        norm = _lower_active_operators(reduced_norm, types)
        transition_norm = _lower_active_operators(
            reduced_norm, types, include_overlap=True
        )

        # [one-/two-body H_D, at-most-two-body T] is connected and contains
        # at most three creation and three destruction operators.  Asking
        # Wick for max_unctr=6 discards only the zero-contraction H2*T2
        # products, which cancel identically in the commutator.  This ordering
        # is important when w has intentionally been given no permutation
        # rules: otherwise Block2 cannot graph-canonicalize two dummy-index
        # forms of that exact zero before the bra is multiplied, producing a
        # spurious 5-RDM in the r/i classes.
        connected_right = (h_dyall_active ^ ket).expand(6).simplify()
        right_commutator = _lower_active_operators(
            _vacuum_reduce(bra * connected_right), types
        )
        connected_left = (bra ^ h_dyall_active).expand(6).simplify()
        left_commutator = _lower_active_operators(
            _vacuum_reduce(connected_left * ket), types
        )

        # The SI one-sided commutator is real when the CAS reference is an
        # exact eigenstate of the active Dyall Hamiltonian.  A converged DMRG
        # MPS has a finite eigen-equation residual, however, so that
        # one-sided form need not itself be Hermitian.  Form its Hermitian
        # part explicitly at the operator/Wick level:
        #
        #   1/2 { T^dagger [H_D,T] + [T^dagger,H_D] T }.
        #
        # This is exactly the SI expression in the eigenstate limit, remains
        # connected and requires no RDM above rank four.  The independently
        # generated left and right branches are retained so execution can
        # verify their adjoint relation; this is deliberately not a final
        # ``.real`` projection of the one-sided numerical result.
        commutator = (0.5 * (right_commutator + left_commutator)).simplify()

        norm_target = parse_tensor(f"norm[{key}]")
        commutator_target = parse_tensor(f"commutator[{key}]")
        norm_code[key] = norm.to_einsum(norm_target)
        transition_norm_code[key] = transition_norm.to_einsum(norm_target)
        right_commutator_code[key] = right_commutator.to_einsum(
            commutator_target
        )
        left_commutator_code[key] = left_commutator.to_einsum(
            commutator_target
        )
        commutator_code[key] = commutator.to_einsum(commutator_target)
        norm_text[key] = repr(norm)
        transition_norm_text[key] = repr(transition_norm)
        right_commutator_text[key] = repr(right_commutator)
        left_commutator_text[key] = repr(left_commutator)
        commutator_text[key] = repr(commutator)

    return _WickEquationBundle(
        norm_code=norm_code,
        transition_norm_code=transition_norm_code,
        right_commutator_code=right_commutator_code,
        left_commutator_code=left_commutator_code,
        commutator_code=commutator_code,
        norm_text=norm_text,
        transition_norm_text=transition_norm_text,
        right_commutator_text=right_commutator_text,
        left_commutator_text=left_commutator_text,
        commutator_text=commutator_text,
    )


def dump_wick_equations(filename: str | None = None) -> str:
    """Return (and optionally write) auditable equations for all eight spaces."""

    equations = _compile_wick_equations()
    sections = []
    for key in SUBSPACE_ORDER:
        sections.extend(
            (
                f"[{key}] perturber\n{_PERTURBER_EXPRESSIONS[key]}",
                f"[{key}] norm expression\n{equations.norm_text[key]}",
                f"[{key}] norm einsum\n{equations.norm_code[key]}",
                f"[{key}] transition norm expression\n"
                f"{equations.transition_norm_text[key]}",
                f"[{key}] transition norm einsum\n"
                f"{equations.transition_norm_code[key]}",
                f"[{key}] right Dyall commutator expression\n"
                f"{equations.right_commutator_text[key]}",
                f"[{key}] right Dyall commutator einsum\n"
                f"{equations.right_commutator_code[key]}",
                f"[{key}] left Dyall commutator expression\n"
                f"{equations.left_commutator_text[key]}",
                f"[{key}] left Dyall commutator einsum\n"
                f"{equations.left_commutator_code[key]}",
                f"[{key}] Hermitian Dyall commutator expression\n"
                f"{equations.commutator_text[key]}",
                f"[{key}] Hermitian Dyall commutator einsum\n"
                f"{equations.commutator_code[key]}",
            )
        )
    text = "\n\n".join(sections) + "\n"
    if filename is not None:
        with open(filename, "w", encoding="utf-8") as handle:
            handle.write(text)
    return text


def _free_index_shape(key: str, eris: spinor_helper._SpinorERIs):
    return tuple(eris.ncore if char in "ij" else eris.nvirt for char in key)


def _orbital_gap(key: str, core_energy, virtual_energy):
    shape = tuple(
        len(core_energy) if char in "ij" else len(virtual_energy)
        for char in key
    )
    gap = np.zeros(shape, dtype=float)
    for axis, char in enumerate(key):
        values = -np.asarray(core_energy) if char in "ij" else np.asarray(
            virtual_energy
        )
        reshape = [1] * len(key)
        reshape[axis] = len(values)
        gap += values.reshape(reshape)
    return gap


def _strict_pair_mask(key: str, shape):
    mask = np.ones(shape, dtype=bool)
    if not shape or any(size == 0 for size in shape):
        return mask
    grid = np.indices(shape, sparse=True)
    for left, right in _PAIR_RESTRICTIONS[key]:
        mask &= grid[left] < grid[right]
    return mask


def _normalize_strong_contraction_groups(
    groups,
    eris,
    core_energy,
    virtual_energy,
    *,
    atol,
    rtol,
):
    """Validate and normalize explicit core/external contraction labels.

    Labels are indexed by the full semicanonical spinor-MO order.  Their
    numerical values have no meaning: equal labels within a core or virtual
    partition identify channels that belong to one strongly-contracted
    orbital.  Active labels are retained only so the public input has one
    unambiguous full-MO shape.
    """

    for name, value in (("atol", atol), ("rtol", rtol)):
        if not np.isfinite(value) or value < 0.0:
            raise ValueError(
                f"strong-contraction group {name} must be finite and "
                "non-negative"
            )
    labels = np.asarray(groups)
    if labels.shape != (eris.nmo,):
        raise ValueError(
            "strong_contraction_groups must have shape "
            f"({eris.nmo},), got {labels.shape}"
        )
    if labels.dtype.kind not in "iufc":
        raise TypeError("strong_contraction_groups must contain integer labels")
    if labels.dtype.kind in "iu":
        integral_labels = labels
    else:
        if labels.dtype.kind == "c" and np.any(labels.imag != 0.0):
            raise ValueError("strong_contraction_groups contains complex labels")
        numeric = np.asarray(labels.real, dtype=float)
        if not np.all(np.isfinite(numeric)):
            raise ValueError(
                "strong_contraction_groups contains non-finite labels"
            )
        integral_labels = np.rint(numeric)
        if np.any(numeric != integral_labels):
            raise ValueError(
                "strong_contraction_groups must contain integer labels"
            )

    ncore = int(eris.ncore)
    nocc = int(eris.nocc)
    if np.asarray(core_energy).shape != (ncore,):
        raise ValueError("core_energy has the wrong shape")
    if np.asarray(virtual_energy).shape != (eris.nmo - nocc,):
        raise ValueError("virtual_energy has the wrong shape")
    normalized = np.empty(eris.nmo, dtype=np.int64)
    partitions = ((0, ncore), (ncore, nocc), (nocc, eris.nmo))
    for start, stop in partitions:
        if start == stop:
            continue
        _unique, inverse = np.unique(
            integral_labels[start:stop],
            return_inverse=True,
        )
        normalized[start:stop] = inverse

    def validate_partition(partition_labels, energies, name):
        energies = np.asarray(energies, dtype=float)
        for group in np.unique(partition_labels):
            selected = energies[partition_labels == group]
            spread = float(np.ptp(selected)) if selected.size else 0.0
            scale = max(1.0, float(np.max(np.abs(selected), initial=0.0)))
            tolerance = float(atol + rtol * scale)
            if spread > tolerance:
                raise ValueError(
                    f"strong-contraction {name} group {int(group)} spans "
                    f"nondegenerate semicanonical energies: spread={spread:.3e}, "
                    f"tolerance={tolerance:.3e}"
                )

    validate_partition(normalized[:ncore], core_energy, "core")
    validate_partition(normalized[nocc:], virtual_energy, "virtual")
    return normalized


def _group_strong_contraction_arrays(
    key,
    arrays,
    orbital_gap,
    ordered,
    groups,
    eris,
    *,
    atol,
    rtol,
):
    """Sum symmetry-partner channels before forming an SC denominator."""

    ordered = np.asarray(ordered, dtype=bool)
    arrays = tuple(np.asarray(array) for array in arrays)
    orbital_gap = np.asarray(orbital_gap, dtype=float)
    if any(array.shape != ordered.shape for array in arrays):
        raise ValueError("strong-contraction arrays and mask have different shapes")
    if orbital_gap.shape != ordered.shape:
        raise ValueError("strong-contraction orbital gap has the wrong shape")

    selected_coordinates = np.column_stack(np.nonzero(ordered))
    raw_dimension = int(selected_coordinates.shape[0])
    if raw_dimension == 0:
        empty_arrays = tuple(
            np.zeros(0, dtype=array.dtype) for array in arrays
        )
        diagnostics = {
            "enabled": True,
            "raw_ordered_dimension": 0,
            "contracted_group_dimension": 0,
            "maximum_orbital_gap_spread": 0.0,
            "orbital_gap_tolerance_at_maximum": float(atol + rtol),
        }
        return empty_arrays, np.zeros(0, dtype=float), diagnostics

    nocc = int(eris.nocc)
    group_columns = []
    for axis, char in enumerate(key):
        if char in "ij":
            partition_groups = groups[: eris.ncore]
        else:
            partition_groups = groups[nocc:]
        group_columns.append(
            partition_groups[selected_coordinates[:, axis]]
        )
    group_keys = np.column_stack(group_columns)
    # A restricted raw pair is ordered by spinor index.  For non-contiguous
    # or otherwise arbitrarily labelled partner groups, canonicalize the
    # corresponding group pair as well so its members cannot split across two
    # denominators merely because of their column order.
    for left, right in _PAIR_RESTRICTIONS[key]:
        low = np.minimum(group_keys[:, left], group_keys[:, right])
        high = np.maximum(group_keys[:, left], group_keys[:, right])
        group_keys[:, left] = low
        group_keys[:, right] = high

    _unique_keys, inverse = np.unique(
        group_keys, axis=0, return_inverse=True
    )
    group_count = int(np.max(inverse)) + 1
    grouped_arrays = []
    for array in arrays:
        grouped = np.zeros(group_count, dtype=array.dtype)
        np.add.at(grouped, inverse, array[ordered])
        grouped_arrays.append(grouped)

    selected_gap = orbital_gap[ordered]
    gap_min = np.full(group_count, np.inf, dtype=float)
    gap_max = np.full(group_count, -np.inf, dtype=float)
    gap_sum = np.zeros(group_count, dtype=float)
    group_size = np.zeros(group_count, dtype=np.int64)
    np.minimum.at(gap_min, inverse, selected_gap)
    np.maximum.at(gap_max, inverse, selected_gap)
    np.add.at(gap_sum, inverse, selected_gap)
    np.add.at(group_size, inverse, 1)
    spreads = gap_max - gap_min
    scales = np.maximum(1.0, np.maximum(np.abs(gap_min), np.abs(gap_max)))
    limits = atol + rtol * scales
    maximum_index = int(np.argmax(spreads))
    if np.any(spreads > limits):
        failed = int(np.argmax(spreads - limits))
        raise ValueError(
            f"subspace {key}: one strong-contraction group spans unequal "
            f"orbital gaps: spread={spreads[failed]:.3e}, "
            f"tolerance={limits[failed]:.3e}"
        )
    grouped_gap = gap_sum / group_size
    diagnostics = {
        "enabled": True,
        "raw_ordered_dimension": raw_dimension,
        "contracted_group_dimension": group_count,
        "maximum_orbital_gap_spread": float(spreads[maximum_index]),
        "orbital_gap_tolerance_at_maximum": float(limits[maximum_index]),
    }
    return tuple(grouped_arrays), grouped_gap, diagnostics


def _require_real(values, *, root, subspace, quantity, atol, rtol):
    values = np.asarray(values)
    if not np.all(np.isfinite(values)):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: {quantity} contains non-finite values"
        )
    if not np.iscomplexobj(values):
        return values.astype(float, copy=False)
    limit = atol + rtol * np.maximum(1.0, np.abs(values.real))
    violation = np.abs(values.imag) - limit
    if np.any(violation > 0.0):
        maximum = float(np.max(np.abs(values.imag)))
        _warn_numerical(
            f"root {root} subspace {subspace}: {quantity} is not real; "
            f"maximum imaginary part = {maximum:.3e}"
        )
    return values.real


def _require_adjoint_pair(
    left,
    right,
    mask,
    *,
    root,
    subspace,
    atol,
    rtol,
):
    """Verify independently generated scalar branches are adjoints."""

    left = np.asarray(left)
    right = np.asarray(right)
    mask = np.asarray(mask, dtype=bool)
    if left.shape != right.shape or left.shape != mask.shape:
        raise ValueError("adjoint-branch arrays or mask have different shapes")
    selected_left = left[mask]
    selected_right = right[mask]
    if not np.all(np.isfinite(selected_left)) or not np.all(
        np.isfinite(selected_right)
    ):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: Dyall commutator branch "
            "contains non-finite values"
        )
    if not selected_left.size:
        return {
            "maximum_adjoint_error": 0.0,
            "maximum_adjoint_error_index": [],
            "reality_limit_at_maximum_error": float(atol + rtol),
            "adjoint_gate_passed": True,
        }

    error = np.abs(selected_left - selected_right.conj())
    limit = atol + rtol * np.maximum(
        1.0, np.maximum(np.abs(selected_left), np.abs(selected_right))
    )
    local_index = int(np.argmax(error))
    selected_flat = np.flatnonzero(mask)
    full_index = np.unravel_index(
        int(selected_flat[local_index]), left.shape
    )
    gate_passed = bool(error[local_index] <= limit[local_index])
    if not gate_passed:
        _warn_numerical(
            f"root {root} subspace {subspace}: independently generated "
            "Dyall commutator branches are not adjoints; maximum error = "
            f"{float(error[local_index]):.3e} at {full_index}"
        )
    return {
        "maximum_adjoint_error": float(error[local_index]),
        "maximum_adjoint_error_index": [int(index) for index in full_index],
        "reality_limit_at_maximum_error": float(limit[local_index]),
        "adjoint_gate_passed": gate_passed,
    }


def _scalar_reality_diagnostics(values, mask, *, atol, rtol):
    """Return the largest imaginary residual of a selected scalar array."""

    values = np.asarray(values)
    mask = np.asarray(mask, dtype=bool)
    selected = values[mask]
    if not selected.size:
        return {
            "maximum_imaginary_part": 0.0,
            "maximum_imaginary_index": [],
            "reality_limit_at_maximum": float(atol + rtol),
            "real_part_at_maximum": 0.0,
            "maximum_imaginary_to_limit_ratio": 0.0,
            "maximum_ratio_index": [],
            "gate_passed": True,
        }
    magnitude = np.abs(selected.imag)
    limits = atol + rtol * np.maximum(1.0, np.abs(selected.real))
    local_index = int(np.argmax(magnitude))
    selected_flat = np.flatnonzero(mask)
    full_index = np.unravel_index(
        int(selected_flat[local_index]), values.shape
    )
    ratio = np.divide(
        magnitude,
        limits,
        out=np.full_like(magnitude, np.inf, dtype=float),
        where=limits > 0.0,
    )
    ratio_index = int(np.argmax(ratio))
    ratio_full_index = np.unravel_index(
        int(selected_flat[ratio_index]), values.shape
    )
    return {
        "maximum_imaginary_part": float(magnitude[local_index]),
        "maximum_imaginary_index": [int(index) for index in full_index],
        "reality_limit_at_maximum": float(limits[local_index]),
        "real_part_at_maximum": float(selected[local_index].real),
        "maximum_imaginary_to_limit_ratio": float(ratio[ratio_index]),
        "maximum_ratio_index": [int(index) for index in ratio_full_index],
        "gate_passed": bool(np.all(magnitude <= limits)),
    }


def _audit_one_sided_si_denominator(
    norm,
    right_commutator,
    one_sided_gap,
    mask,
    *,
    root,
    subspace,
    gap_atol,
    gap_rtol,
    numerator_noise_allowance,
    energy_imag_l1_tol,
    projection_shift_l1_tol,
    denominator_tol,
    enforce,
):
    """Audit the literal SI denominator with a bounded near-null exception.

    Dividing a roundoff-sized imaginary numerator by a nearly null perturber
    norm can make the raw gap look complex even for an exact eigenvector.  A
    direct gap-gate failure is therefore accepted only when the numerator is
    within an explicit absolute noise allowance *and* both the imaginary
    energy and real-projection shift have small cancellation-free L1 bounds.
    """

    norm = np.asarray(norm)
    right_commutator = np.asarray(right_commutator)
    one_sided_gap = np.asarray(one_sided_gap)
    mask = np.asarray(mask, dtype=bool)
    if not (
        norm.shape
        == right_commutator.shape
        == one_sided_gap.shape
        == mask.shape
    ):
        raise ValueError("one-sided SI audit arrays or mask have different shapes")

    tolerances = {
        "gap_atol": float(gap_atol),
        "gap_rtol": float(gap_rtol),
        "numerator_noise_allowance": float(numerator_noise_allowance),
        "energy_imag_l1_tol": float(energy_imag_l1_tol),
        "projection_shift_l1_tol": float(projection_shift_l1_tol),
    }
    if any(
        not np.isfinite(value) or value < 0.0
        for value in tolerances.values()
    ):
        raise ValueError("strict-SI audit tolerances must be finite and non-negative")

    selected_norm = np.asarray(norm[mask].real, dtype=float)
    selected_numerator = right_commutator[mask]
    selected_gap = one_sided_gap[mask]
    selected_flat = np.flatnonzero(mask)
    if not selected_norm.size:
        diagnostics = {
            **_scalar_reality_diagnostics(
                one_sided_gap,
                mask,
                atol=tolerances["gap_atol"],
                rtol=tolerances["gap_rtol"],
            ),
            "strict_si_compatible": True,
            "direct_gap_gate_passed": True,
            "raw_numerator_gate_passed": True,
            "positive_denominator_gate_passed": True,
            "roundoff_limited_near_null_count": 0,
            "roundoff_limited_near_null_indices": [],
            "maximum_numerator_imaginary_part": 0.0,
            "maximum_numerator_imaginary_index": [],
            "maximum_numerator_imaginary_to_limit_ratio": 0.0,
            "maximum_numerator_ratio_index": [],
            "imaginary_energy_l1": 0.0,
            "imaginary_energy_l1_tolerance": tolerances[
                "energy_imag_l1_tol"
            ],
            "imaginary_energy_l1_gate_passed": True,
            "real_projection_shift_l1": 0.0,
            "real_projection_shift_l1_tolerance": tolerances[
                "projection_shift_l1_tol"
            ],
            "real_projection_shift_l1_gate_passed": True,
            "numerator_noise_allowance": tolerances[
                "numerator_noise_allowance"
            ],
            "numerical_policy": "explicit-calibrated-numerator-allowance",
        }
        return selected_norm, diagnostics

    if (
        not np.all(np.isfinite(selected_norm))
        or not np.all(np.isfinite(selected_numerator))
        or not np.all(np.isfinite(selected_gap))
    ):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: one-sided SI audit contains "
            "non-finite inputs"
        )

    gap_imag = np.abs(selected_gap.imag)
    gap_limit = tolerances["gap_atol"] + tolerances["gap_rtol"] * np.maximum(
        1.0, np.abs(selected_gap.real)
    )
    numerator_imag = np.abs(selected_numerator.imag)
    numerator_limit = (
        tolerances["numerator_noise_allowance"] + selected_norm * gap_limit
    )
    direct_gap_pass = gap_imag <= gap_limit
    numerator_pass = numerator_imag <= numerator_limit
    near_null = (
        ~direct_gap_pass
        & (
            selected_norm * gap_limit
            < tolerances["numerator_noise_allowance"]
        )
        & numerator_pass
    )
    gap_accepted = direct_gap_pass | near_null
    positive = selected_gap.real > denominator_tol

    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        complex_energy = -selected_norm / selected_gap
        projected_energy = -selected_norm / selected_gap.real
    finite_energies = np.all(np.isfinite(complex_energy)) and np.all(
        np.isfinite(projected_energy)
    )
    if not finite_energies:
        raise FloatingPointError(
            f"root {root} subspace {subspace}: one-sided SI energy audit "
            "produced non-finite values"
        )
    imaginary_energy_l1 = float(np.sum(np.abs(complex_energy.imag)))
    projection_shift_l1 = float(
        np.sum(np.abs(projected_energy - complex_energy.real))
    )
    energy_imag_pass = (
        imaginary_energy_l1 <= tolerances["energy_imag_l1_tol"]
    )
    projection_shift_pass = (
        projection_shift_l1 <= tolerances["projection_shift_l1_tol"]
    )
    strict_compatible = bool(
        np.all(gap_accepted)
        and np.all(numerator_pass)
        and np.all(positive)
        and finite_energies
        and energy_imag_pass
        and projection_shift_pass
    )

    def full_index(local_index):
        return [
            int(index)
            for index in np.unravel_index(
                int(selected_flat[int(local_index)]), mask.shape
            )
        ]

    numerator_ratio = np.divide(
        numerator_imag,
        numerator_limit,
        out=np.full_like(numerator_imag, np.inf, dtype=float),
        where=numerator_limit > 0.0,
    )
    numerator_max = int(np.argmax(numerator_imag))
    numerator_ratio_max = int(np.argmax(numerator_ratio))
    near_null_local = np.flatnonzero(near_null)
    diagnostics = {
        **_scalar_reality_diagnostics(
            one_sided_gap,
            mask,
            atol=tolerances["gap_atol"],
            rtol=tolerances["gap_rtol"],
        ),
        "strict_si_compatible": strict_compatible,
        "direct_gap_gate_passed": bool(np.all(direct_gap_pass)),
        "raw_numerator_gate_passed": bool(np.all(numerator_pass)),
        "positive_denominator_gate_passed": bool(np.all(positive)),
        "roundoff_limited_near_null_count": int(len(near_null_local)),
        "roundoff_limited_near_null_indices": [
            full_index(index) for index in near_null_local
        ],
        "maximum_numerator_imaginary_part": float(
            numerator_imag[numerator_max]
        ),
        "maximum_numerator_imaginary_index": full_index(numerator_max),
        "maximum_numerator_imaginary_to_limit_ratio": float(
            numerator_ratio[numerator_ratio_max]
        ),
        "maximum_numerator_ratio_index": full_index(numerator_ratio_max),
        "imaginary_energy_l1": imaginary_energy_l1,
        "imaginary_energy_l1_tolerance": tolerances["energy_imag_l1_tol"],
        "imaginary_energy_l1_gate_passed": bool(energy_imag_pass),
        "real_projection_shift_l1": projection_shift_l1,
        "real_projection_shift_l1_tolerance": tolerances[
            "projection_shift_l1_tol"
        ],
        "real_projection_shift_l1_gate_passed": bool(projection_shift_pass),
        "numerator_noise_allowance": tolerances[
            "numerator_noise_allowance"
        ],
        "numerical_policy": "explicit-calibrated-numerator-allowance",
    }
    if enforce and not strict_compatible:
        _warn_numerical(
            f"root {root} subspace {subspace}: one-sided SI denominator "
            "audit failed; "
            f"max |Im gap|={float(np.max(gap_imag)):.3e}, "
            f"max numerator ratio={float(np.max(numerator_ratio)):.3e}, "
            f"Im(E) L1={imaginary_energy_l1:.3e}, "
            f"projection shift L1={projection_shift_l1:.3e}"
        )
    return selected_gap.real, diagnostics


def _validate_zero_norm_commutator(
    values,
    mask,
    *,
    root,
    subspace,
    atol,
    rtol,
):
    """Gate and describe the Hermitian numerator of discarded perturbers."""

    values = np.asarray(values)
    mask = np.asarray(mask, dtype=bool)
    if values.shape != mask.shape:
        raise ValueError("zero-norm commutator array and mask have different shapes")
    selected = values[mask]
    if not np.all(np.isfinite(selected)):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: zero-norm Dyall commutator "
            "contains non-finite values"
        )
    if not selected.size:
        return {
            "maximum_absolute_value": 0.0,
            "maximum_absolute_index": [],
            "acceptance_limit_at_maximum": float(atol + rtol),
            "gate_passed": True,
        }

    magnitude = np.abs(selected)
    limit = atol + rtol * np.maximum(1.0, np.abs(selected.real))
    local_index = int(np.argmax(magnitude))
    selected_flat = np.flatnonzero(mask)
    full_index = np.unravel_index(
        int(selected_flat[local_index]), values.shape
    )
    gate_passed = bool(magnitude[local_index] <= limit[local_index])
    if not gate_passed:
        _warn_numerical(
            f"root {root} subspace {subspace}: a zero-norm perturber has "
            f"nonzero Dyall commutator {float(magnitude[local_index]):.3e} "
            f"at {full_index}"
        )
    return {
        "maximum_absolute_value": float(magnitude[local_index]),
        "maximum_absolute_index": [int(index) for index in full_index],
        "acceptance_limit_at_maximum": float(limit[local_index]),
        "gate_passed": gate_passed,
    }


def _execution_context(eris, pdms, *, overlap=None):
    context = {
        "deltaAA": np.eye(eris.ncas),
        "deltaII": np.eye(eris.ncore),
        "deltaEE": np.eye(eris.nvirt),
    }
    for rank, density in enumerate(pdms, start=1):
        context[f"dm{rank}{'A' * (2 * rank)}"] = density
    if overlap is not None:
        context["dm0"] = np.asarray(overlap)
    for key in _H1_KEYS:
        value = eris.get_h1eff(key)
        context[f"h{key}"] = value
        context[f"hc{key}"] = value.conj()
    for key in _W_KEYS:
        value = eris.get_phys(key)
        context[f"w{key}"] = value
        context[f"wc{key}"] = value.conj()
    return context


def _evaluate_wick_subspaces(
    eris,
    pdms,
    core_energy,
    virtual_energy,
    *,
    root=0,
    scalar_atol=1.0e-10,
    scalar_rtol=1.0e-9,
    norm_tol=1.0e-14,
    denominator_tol=1.0e-12,
    denominator_mode="strict_si",
    si_gap_imag_atol=1.0e-10,
    si_gap_imag_rtol=1.0e-9,
    si_numerator_noise_allowance=1.0e-12,
    si_energy_imag_l1_tol=1.0e-10,
    si_projection_shift_l1_tol=1.0e-12,
    contraction_backend=_DEFAULT_CONTRACTION_BACKEND,
    strong_contraction_groups=None,
    strong_contraction_group_atol=1.0e-10,
    strong_contraction_group_rtol=1.0e-9,
    return_arrays=False,
    return_timings=False,
    return_diagnostics=False,
):
    """Evaluate all generated equations in the supplied semicanonical basis."""

    denominator_mode = _normalize_denominator_mode(denominator_mode)
    contraction_backend = _normalize_contraction_backend(contraction_backend)
    if strong_contraction_groups is not None and return_arrays:
        raise NotImplementedError(
            "return_arrays=True is not yet available with explicit "
            "strong-contraction groups"
        )
    normalized_groups = None
    if strong_contraction_groups is not None:
        normalized_groups = _normalize_strong_contraction_groups(
            strong_contraction_groups,
            eris,
            core_energy,
            virtual_energy,
            atol=strong_contraction_group_atol,
            rtol=strong_contraction_group_rtol,
        )
    if contraction_backend == "pytblis":
        _validate_tblis_operand_dtypes(
            [(f"h{key}", eris.get_h1eff(key)) for key in _H1_KEYS]
            + [(f"w{key}", eris.get_phys(key)) for key in _W_KEYS]
            + [(f"dm{rank}", density) for rank, density in enumerate(pdms, 1)]
        )
    # Block2 emits source containing ``np.einsum``.  That global name is
    # resolved only here at exec time, so the cached source is backend-agnostic.
    wick_globals = {
        "np": _wick_einsum_namespace(contraction_backend),
    }
    equations = _compile_wick_equations()
    base_context = _execution_context(eris, pdms)
    sub_eners = {}
    sub_norms = {}
    sub_gaps = {}
    arrays = {}
    timings = {}
    realness_diagnostics = {}

    for key in SUBSPACE_ORDER:
        subspace_start = time.perf_counter()
        shape = _free_index_shape(key, eris)
        integral_dtypes = tuple(
            eris.get_h1eff(block).dtype for block in _H1_KEYS
        ) + tuple(eris.get_phys(block).dtype for block in _W_KEYS)
        dtype = np.result_type(
            np.complex128,
            *integral_dtypes,
            *(density.dtype for density in pdms),
        )
        norm = np.zeros(shape, dtype=dtype)
        right_commutator = np.zeros(shape, dtype=dtype)
        left_commutator = np.zeros(shape, dtype=dtype)
        local_context = dict(base_context)
        local_context.update(norm=norm)
        exec(equations.norm_code[key], wick_globals, local_context)
        local_context["commutator"] = right_commutator
        exec(
            equations.right_commutator_code[key],
            wick_globals,
            local_context,
        )
        local_context["commutator"] = left_commutator
        exec(
            equations.left_commutator_code[key],
            wick_globals,
            local_context,
        )
        ordered = _strict_pair_mask(key, shape)
        branch_diagnostics = _require_adjoint_pair(
            left_commutator,
            right_commutator,
            ordered,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        orbital_gap = _orbital_gap(key, core_energy, virtual_energy)
        raw_ordered_dimension = int(np.count_nonzero(ordered))
        if normalized_groups is None:
            grouping_diagnostics = {
                "enabled": False,
                "raw_ordered_dimension": raw_ordered_dimension,
                "contracted_group_dimension": raw_ordered_dimension,
                "maximum_orbital_gap_spread": 0.0,
                "orbital_gap_tolerance_at_maximum": float(
                    strong_contraction_group_atol
                    + strong_contraction_group_rtol
                ),
            }
        else:
            grouped, orbital_gap, grouping_diagnostics = (
                _group_strong_contraction_arrays(
                    key,
                    (norm, right_commutator, left_commutator),
                    orbital_gap,
                    ordered,
                    normalized_groups,
                    eris,
                    atol=strong_contraction_group_atol,
                    rtol=strong_contraction_group_rtol,
                )
            )
            norm, right_commutator, left_commutator = grouped
            shape = norm.shape
            ordered = np.ones(shape, dtype=bool)
        orbital_gap = orbital_gap.astype(dtype, copy=False)

        # This reconciles two independently contracted representations of the
        # *same one-sided* scalar.  In exact arithmetic left.conj() == right,
        # so unlike the Hermitian half-sum below it does not remove a physical
        # one-sided imaginary residual.  Explicit symmetry-partner channels,
        # when requested, have already been summed above: the nonlinear SC
        # denominator must be formed only after that sum.
        si_right_commutator = 0.5 * (
            right_commutator + left_commutator.conj()
        )
        commutator = 0.5 * (right_commutator + left_commutator)

        selected_norm = norm[ordered]
        selected_norm = _require_real(
            selected_norm,
            root=root,
            subspace=key,
            quantity="norm",
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        if np.any(selected_norm < -norm_tol):
            minimum = float(np.min(selected_norm))
            _warn_numerical(
                f"root {root} subspace {key}: negative norm {minimum:.3e}"
            )

        nonzero_flat = selected_norm > norm_tol
        nonzero = np.zeros(shape, dtype=bool)
        nonzero[ordered] = nonzero_flat
        selected_commutator = _require_real(
            commutator[nonzero],
            root=root,
            subspace=key,
            quantity="Hermitian Dyall commutator",
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        zero_norm = ordered & ~nonzero
        zero_norm_diagnostics = _validate_zero_norm_commutator(
            commutator,
            zero_norm,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        right_zero_norm_diagnostics = _validate_zero_norm_commutator(
            right_commutator,
            zero_norm,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        left_zero_norm_diagnostics = _validate_zero_norm_commutator(
            left_commutator,
            zero_norm,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        one_sided_gap = orbital_gap.copy()
        hermitianized_gap = orbital_gap.copy()
        if np.any(nonzero):
            retained_norm = selected_norm[nonzero_flat]
            one_sided_gap[nonzero] += (
                si_right_commutator[nonzero] / retained_norm
            )
            hermitianized_gap[nonzero] += (
                selected_commutator / retained_norm
            )
            si_real_gap, one_sided_diagnostics = (
                _audit_one_sided_si_denominator(
                    norm,
                    si_right_commutator,
                    one_sided_gap,
                    nonzero,
                    root=root,
                    subspace=key,
                    gap_atol=si_gap_imag_atol,
                    gap_rtol=si_gap_imag_rtol,
                    numerator_noise_allowance=si_numerator_noise_allowance,
                    energy_imag_l1_tol=si_energy_imag_l1_tol,
                    projection_shift_l1_tol=si_projection_shift_l1_tol,
                    denominator_tol=denominator_tol,
                    enforce=denominator_mode == "strict_si",
                )
            )
            if denominator_mode == "strict_si":
                real_gap = si_real_gap
                selected_gap = one_sided_gap.copy()
            else:
                real_gap = _require_real(
                    hermitianized_gap[nonzero],
                    root=root,
                    subspace=key,
                    quantity="Hermitianized Dyall denominator",
                    atol=scalar_atol,
                    rtol=scalar_rtol,
                )
                selected_gap = hermitianized_gap.copy()
            selected_gap[nonzero] = real_gap
            if np.any(real_gap <= denominator_tol):
                minimum = float(np.min(real_gap))
                raise FloatingPointError(
                    f"root {root} subspace {key}: non-positive or near-zero "
                    f"Dyall denominator {minimum:.3e}"
                )
            contribution = -np.sum(selected_norm[nonzero_flat] / real_gap)
            gap_min = float(np.min(real_gap))
            gap_max = float(np.max(real_gap))
        else:
            contribution = 0.0
            gap_min = np.nan
            gap_max = np.nan
            selected_gap = (
                one_sided_gap
                if denominator_mode == "strict_si"
                else hermitianized_gap
            )
            _si_real_gap, one_sided_diagnostics = (
                _audit_one_sided_si_denominator(
                    norm,
                    si_right_commutator,
                    one_sided_gap,
                    nonzero,
                    root=root,
                    subspace=key,
                    gap_atol=si_gap_imag_atol,
                    gap_rtol=si_gap_imag_rtol,
                    numerator_noise_allowance=si_numerator_noise_allowance,
                    energy_imag_l1_tol=si_energy_imag_l1_tol,
                    projection_shift_l1_tol=si_projection_shift_l1_tol,
                    denominator_tol=denominator_tol,
                    enforce=denominator_mode == "strict_si",
                )
            )

        class_diagnostics = {
            **branch_diagnostics,
            "contraction_backend": contraction_backend,
            "denominator_mode": denominator_mode,
            "selected_denominator_source": (
                "reconciled_right_si"
                if denominator_mode == "strict_si"
                else "hermitian_half_sum"
            ),
            "norm": _scalar_reality_diagnostics(
                norm, ordered, atol=scalar_atol, rtol=scalar_rtol
            ),
            "hermitian_commutator": _scalar_reality_diagnostics(
                commutator, ordered, atol=scalar_atol, rtol=scalar_rtol
            ),
            "one_sided_denominator": one_sided_diagnostics,
            "hermitianized_denominator": _scalar_reality_diagnostics(
                hermitianized_gap,
                nonzero,
                atol=scalar_atol,
                rtol=scalar_rtol,
            ),
            "zero_norm_hermitian_commutator": zero_norm_diagnostics,
            "zero_norm_right_commutator": right_zero_norm_diagnostics,
            "zero_norm_left_commutator": left_zero_norm_diagnostics,
            "strong_contraction_grouping": grouping_diagnostics,
            "minimum_retained_norm": (
                float(np.min(selected_norm[nonzero_flat]))
                if np.any(nonzero_flat)
                else None
            ),
            "ordered_dimension": int(np.count_nonzero(ordered)),
            "raw_ordered_dimension": raw_ordered_dimension,
            "retained_dimension": int(np.count_nonzero(nonzero_flat)),
            "discarded_zero_norm_dimension": int(np.count_nonzero(zero_norm)),
        }
        realness_diagnostics[key] = class_diagnostics

        sub_eners[key] = float(contribution)
        sub_norms[key] = float(np.sum(np.maximum(selected_norm, 0.0)))
        sub_gaps[key] = (gap_min, gap_max)
        if return_arrays:
            arrays[key] = {
                "norm": norm,
                "commutator": commutator,
                "right_commutator": right_commutator,
                "left_commutator": left_commutator,
                "si_right_commutator": si_right_commutator,
                "selected_commutator": (
                    si_right_commutator
                    if denominator_mode == "strict_si"
                    else commutator
                ),
                "orbital_gap": _orbital_gap(
                    key, core_energy, virtual_energy
                ),
                "denominator": selected_gap,
                "one_sided_denominator": one_sided_gap,
                "hermitianized_denominator": hermitianized_gap,
                "ordered": ordered,
                "nonzero": nonzero,
            }
        timings[key] = time.perf_counter() - subspace_start

    root_imaginary_energy_l1 = float(
        sum(
            diagnostics["one_sided_denominator"]["imaginary_energy_l1"]
            for diagnostics in realness_diagnostics.values()
        )
    )
    root_projection_shift_l1 = float(
        sum(
            diagnostics["one_sided_denominator"]["real_projection_shift_l1"]
            for diagnostics in realness_diagnostics.values()
        )
    )
    root_energy_gate_passed = bool(
        root_imaginary_energy_l1 <= si_energy_imag_l1_tol
    )
    root_projection_gate_passed = bool(
        root_projection_shift_l1 <= si_projection_shift_l1_tol
    )
    root_strict_si_compatible = bool(
        root_energy_gate_passed
        and root_projection_gate_passed
        and all(
            diagnostics["one_sided_denominator"]["strict_si_compatible"]
            for diagnostics in realness_diagnostics.values()
        )
    )
    root_audit = {
        "strict_si_compatible": root_strict_si_compatible,
        "imaginary_energy_l1": root_imaginary_energy_l1,
        "imaginary_energy_l1_tolerance": float(si_energy_imag_l1_tol),
        "imaginary_energy_l1_gate_passed": root_energy_gate_passed,
        "real_projection_shift_l1": root_projection_shift_l1,
        "real_projection_shift_l1_tolerance": float(
            si_projection_shift_l1_tol
        ),
        "real_projection_shift_l1_gate_passed": root_projection_gate_passed,
    }
    for diagnostics in realness_diagnostics.values():
        diagnostics["root_one_sided_si_audit"] = dict(root_audit)
    if denominator_mode == "strict_si" and not root_strict_si_compatible:
        _warn_numerical(
            f"root {root}: aggregate one-sided SI denominator audit failed; "
            f"Im(E) L1={root_imaginary_energy_l1:.3e}, "
            f"projection shift L1={root_projection_shift_l1:.3e}"
        )

    result = (sub_eners, sub_norms, sub_gaps)
    if return_arrays:
        result += (arrays,)
    if return_timings:
        result += (timings,)
    if return_diagnostics:
        result += (realness_diagnostics,)
    return result


def _maximum_abs(array) -> float:
    array = np.asarray(array)
    return float(np.max(np.abs(array), initial=0.0))


def _leading_chunks(shape, dtype, work_memory):
    """Yield leading-index chunks whose dense temporaries fit in memory.

    A transposed RDM is generally non-contiguous, so flattening it may itself
    allocate the full tensor.  Leading-index tuples keep both the original and
    transposed operands as views while bounding every arithmetic temporary.
    """

    shape = tuple(int(size) for size in shape)
    if not shape or 0 in shape:
        yield (...,)
        return
    itemsize = np.dtype(dtype).itemsize
    # Allow two arithmetic temporaries (e.g. conjugate plus difference).
    max_elements = max(1, int(work_memory) // (2 * itemsize))
    trailing = int(np.prod(shape, dtype=np.int64))
    prefix_rank = 0
    while trailing > max_elements and prefix_rank < len(shape):
        trailing //= shape[prefix_rank]
        prefix_rank += 1
    if prefix_rank == 0:
        yield (...,)
        return
    suffix = (slice(None),) * (len(shape) - prefix_rank)
    for prefix in np.ndindex(shape[:prefix_rank]):
        yield prefix + suffix


def _all_finite_chunked(array, work_memory):
    array = np.asarray(array)
    return all(
        bool(np.all(np.isfinite(array[index])))
        for index in _leading_chunks(array.shape, array.dtype, work_memory)
    )


def _maximum_abs_chunked(array, work_memory) -> float:
    array = np.asarray(array)
    maximum = 0.0
    for index in _leading_chunks(array.shape, array.dtype, work_memory):
        maximum = max(maximum, _maximum_abs(array[index]))
    return maximum


def _maximum_abs_relation(
    left,
    right,
    *,
    sign,
    conjugate_right=False,
    work_memory,
) -> float:
    """Return max(abs(left + sign * right)) using bounded temporaries."""

    left = np.asarray(left)
    right = np.asarray(right)
    if left.shape != right.shape:
        raise ValueError("RDM relation operands have different shapes")
    maximum = 0.0
    for index in _leading_chunks(left.shape, left.dtype, work_memory):
        right_chunk = right[index]
        if conjugate_right:
            right_chunk = right_chunk.conj()
        difference = left[index] + sign * right_chunk
        maximum = max(maximum, _maximum_abs(difference))
    return maximum


def validate_pdms(
    pdms,
    ncas,
    nelec,
    *,
    atol=1.0e-9,
    rtol=1.0e-8,
    work_memory=512 * 2**20,
):
    """Validate raw SGF 1--4 particle RDM shapes, order, and contractions.

    ``work_memory`` bounds arithmetic temporaries used by the symmetry checks.
    This matters for a 16-spinor complex 4-RDM, whose dense storage alone is
    64 GiB.  It does not relax or sample any validation condition.

    Finite relation residuals beyond tolerance emit
    :class:`MRPTNumericalWarning` and are retained in the diagnostics.  Invalid
    shapes, nonnumeric arrays, and non-finite values remain hard errors.
    """

    if not isinstance(pdms, (tuple, list)) or len(pdms) != 4:
        raise ValueError("pdms must be a (dm1, dm2, dm3, dm4) sequence")
    ncas = int(ncas)
    nelec = int(nelec)
    work_memory = int(work_memory)
    if work_memory <= 0:
        raise ValueError("work_memory must be positive")
    checked = []
    diagnostics = {}
    for rank, density in enumerate(pdms, start=1):
        density = np.asarray(density)
        expected_shape = (ncas,) * (2 * rank)
        if density.shape != expected_shape:
            raise ValueError(
                f"dm{rank} must have shape {expected_shape}, got {density.shape}"
            )
        if not np.issubdtype(density.dtype, np.number):
            raise TypeError(f"dm{rank} must be numeric")
        if not _all_finite_chunked(density, work_memory):
            raise ValueError(f"dm{rank} contains non-finite values")

        creator_error = 0.0
        annihilator_error = 0.0
        for axis in range(rank - 1):
            creator_error = max(
                creator_error,
                _maximum_abs_relation(
                    density,
                    density.swapaxes(axis, axis + 1),
                    sign=1.0,
                    work_memory=work_memory,
                ),
            )
            annihilator_axis = rank + axis
            annihilator_error = max(
                annihilator_error,
                _maximum_abs_relation(
                    density,
                    density.swapaxes(
                        annihilator_axis, annihilator_axis + 1
                    ),
                    sign=1.0,
                    work_memory=work_memory,
                ),
            )

        hermitian_axes = tuple(range(2 * rank - 1, rank - 1, -1))
        hermitian_axes += tuple(range(rank - 1, -1, -1))
        hermiticity_error = _maximum_abs_relation(
            density,
            density.transpose(hermitian_axes),
            sign=-1.0,
            conjugate_right=True,
            work_memory=work_memory,
        )
        scale = max(1.0, _maximum_abs_chunked(density, work_memory))
        tolerance = atol + rtol * scale
        symmetry_gate_passed = bool(
            max(creator_error, annihilator_error, hermiticity_error)
            <= tolerance
        )
        if not symmetry_gate_passed:
            _warn_numerical(
                f"dm{rank} violates raw SGF antisymmetry/Hermiticity: "
                f"creator={creator_error:.3e}, annihilator={annihilator_error:.3e}, "
                f"Hermiticity={hermiticity_error:.3e}"
            )
        diagnostics[f"dm{rank}"] = {
            "shape": list(density.shape),
            "creator_antisymmetry_error": creator_error,
            "annihilator_antisymmetry_error": annihilator_error,
            "hermiticity_error": hermiticity_error,
            "symmetry_tolerance": float(tolerance),
            "symmetry_gate_passed": symmetry_gate_passed,
        }
        checked.append(density)

    trace = np.trace(checked[0])
    trace_error = abs(trace - nelec)
    trace_tolerance = atol + rtol * max(1, nelec)
    trace_gate_passed = bool(trace_error <= trace_tolerance)
    if not trace_gate_passed:
        _warn_numerical(
            f"dm1 trace is inconsistent with {nelec} electrons: "
            f"error={trace_error:.3e}"
        )
    diagnostics["dm1"]["trace_error"] = float(trace_error)
    diagnostics["dm1"]["trace"] = float(trace.real)
    diagnostics["dm1"]["trace_imag"] = float(trace.imag)
    diagnostics["dm1"]["trace_tolerance"] = float(trace_tolerance)
    diagnostics["dm1"]["trace_gate_passed"] = trace_gate_passed

    for rank in range(2, 5):
        contracted = np.trace(
            checked[rank - 1], axis1=rank - 1, axis2=rank
        )
        expected = (nelec - rank + 1) * checked[rank - 2]
        error = _maximum_abs_relation(
            contracted,
            expected,
            sign=-1.0,
            work_memory=work_memory,
        )
        scale = max(1.0, _maximum_abs_chunked(expected, work_memory))
        contraction_tolerance = atol + rtol * scale
        contraction_gate_passed = bool(error <= contraction_tolerance)
        if not contraction_gate_passed:
            _warn_numerical(
                f"dm{rank}->dm{rank - 1} particle-number contraction "
                f"failed: error={error:.3e}"
            )
        diagnostics[f"dm{rank}"]["contraction_error"] = error
        diagnostics[f"dm{rank}"]["contraction_tolerance"] = float(
            contraction_tolerance
        )
        diagnostics[f"dm{rank}"][
            "contraction_gate_passed"
        ] = contraction_gate_passed
    return tuple(checked), diagnostics


def _root_ket(dmrgci, root):
    driver = getattr(dmrgci, "driver", None)
    kets = getattr(dmrgci, "kets", None)
    if driver is None or kets is None:
        raise RuntimeError(
            "the converged pyblock2 driver/MPS must remain open while forming RDMs"
        )
    root = int(root)
    if not 0 <= root < len(kets):
        raise IndexError(
            f"DMRG root {root} is outside the available range [0, {len(kets)})"
        )
    return driver, kets[root]


def _make_rdm(dmrgci, root, rank):
    driver, ket = _root_ket(dmrgci, root)
    method = getattr(driver, f"get_{rank}pdm", None)
    kwargs = {
        "site_type": int(getattr(dmrgci, "npdm_site_type", 0)),
        "cutoff": float(getattr(dmrgci, "npdm_cutoff", 1.0e-24)),
    }
    if callable(method):
        density = method(ket, **kwargs)
    else:  # Compatibility fallback, using the inspected installed signature.
        method = getattr(driver, "get_npdm", None)
        if not callable(method):
            raise RuntimeError(
                f"the installed pyblock2 driver has no {rank}-RDM interface"
            )
        density = method(ket, pdm_type=rank, **kwargs)
    density = np.asarray(density)
    ncas = int(getattr(dmrgci, "ncas"))
    expected_shape = (ncas,) * (2 * rank)
    if density.shape != expected_shape:
        raise ValueError(
            f"Block2 root {root} {rank}-RDM has shape {density.shape}; "
            f"expected raw SGF shape {expected_shape}"
        )
    if not np.iscomplexobj(density):
        density = density.astype(np.complex128)
    return density


def make_rdm1(dmrgci, root=0):
    """Return raw ``<C[p]D[q]>`` for one selected SGF MPS root."""

    return _make_rdm(dmrgci, root, 1)


def make_rdm2(dmrgci, root=0):
    """Return raw ``<C[p]C[q]D[s]D[r]>`` for one selected MPS root."""

    return _make_rdm(dmrgci, root, 2)


def make_rdm3(dmrgci, root=0):
    """Return the explicit raw SGF 3-particle RDM for one MPS root."""

    return _make_rdm(dmrgci, root, 3)


def make_rdm4(dmrgci, root=0):
    """Return the explicit raw SGF 4-particle RDM for one MPS root."""

    return _make_rdm(dmrgci, root, 4)


def make_dm1234(dmrgci, root=0):
    """Obtain explicit, unapproximated raw 1--4 RDMs for one selected root."""

    return tuple(_make_rdm(dmrgci, root, rank) for rank in range(1, 5))


def _rotate_eris(eris, rotation):
    rotation = np.asarray(rotation)
    h1e = rotation.T.conj() @ eris.h1e @ rotation
    h1eff = rotation.T.conj() @ eris.h1eff @ rotation
    eri = np.einsum(
        "ap,bq,cr,ds,abcd->pqrs",
        rotation.conj(),
        rotation,
        rotation.conj(),
        rotation,
        eris.pppp,
        optimize=True,
    )
    return spinor_helper.init_eris(
        h1e,
        eri,
        eris.ncore,
        eris.ncas,
        h1eff=h1eff,
        frozen=0,
        copy=False,
        check=True,
    )


