def _evaluate_wick_subspaces(
    eris,
    pdms,
    core_energy,
    virtual_energy,
    *,
    root=0,
    scalar_atol=1.0e-10,
    scalar_rtol=1.0e-9,
    norm_tol=1.0e-14,
    denominator_tol=1.0e-12,
    denominator_mode="strict_si",
    si_gap_imag_atol=1.0e-10,
    si_gap_imag_rtol=1.0e-9,
    si_numerator_noise_allowance=1.0e-12,
    si_energy_imag_l1_tol=1.0e-10,
    si_projection_shift_l1_tol=1.0e-12,
    contraction_backend=_DEFAULT_CONTRACTION_BACKEND,
    strong_contraction_groups=None,
    strong_contraction_group_atol=1.0e-10,
    strong_contraction_group_rtol=1.0e-9,
    return_arrays=False,
    return_timings=False,
    return_diagnostics=False,
):
    """Evaluate all generated equations in the supplied semicanonical basis."""

    denominator_mode = _normalize_denominator_mode(denominator_mode)
    contraction_backend = _normalize_contraction_backend(contraction_backend)
    if strong_contraction_groups is not None and return_arrays:
        raise NotImplementedError(
            "return_arrays=True is not yet available with explicit "
            "strong-contraction groups"
        )
    normalized_groups = None
    if strong_contraction_groups is not None:
        normalized_groups = _normalize_strong_contraction_groups(
            strong_contraction_groups,
            eris,
            core_energy,
            virtual_energy,
            atol=strong_contraction_group_atol,
            rtol=strong_contraction_group_rtol,
        )
    if contraction_backend == "pytblis":
        _validate_tblis_operand_dtypes(
            [(f"h{key}", eris.get_h1eff(key)) for key in _H1_KEYS]
            + [(f"w{key}", eris.get_phys(key)) for key in _W_KEYS]
            + [(f"dm{rank}", density) for rank, density in enumerate(pdms, 1)]
        )
    # Block2 emits source containing ``np.einsum``.  That global name is
    # resolved only here at exec time, so the cached source is backend-agnostic.
    wick_globals = {
        "np": _wick_einsum_namespace(contraction_backend),
    }
    equations = _compile_wick_equations()
    base_context = _execution_context(eris, pdms)
    sub_eners = {}
    sub_norms = {}
    sub_gaps = {}
    arrays = {}
    timings = {}
    realness_diagnostics = {}

    for key in SUBSPACE_ORDER:
        subspace_start = time.perf_counter()
        shape = _free_index_shape(key, eris)
        integral_dtypes = tuple(
            eris.get_h1eff(block).dtype for block in _H1_KEYS
        ) + tuple(eris.get_phys(block).dtype for block in _W_KEYS)
        dtype = np.result_type(
            np.complex128,
            *integral_dtypes,
            *(density.dtype for density in pdms),
        )
        norm = np.zeros(shape, dtype=dtype)
        right_commutator = np.zeros(shape, dtype=dtype)
        left_commutator = np.zeros(shape, dtype=dtype)
        local_context = dict(base_context)
        local_context.update(norm=norm)
        exec(equations.norm_code[key], wick_globals, local_context)
        local_context["commutator"] = right_commutator
        exec(
            equations.right_commutator_code[key],
            wick_globals,
            local_context,
        )
        local_context["commutator"] = left_commutator
        exec(
            equations.left_commutator_code[key],
            wick_globals,
            local_context,
        )
        ordered = _strict_pair_mask(key, shape)
        branch_diagnostics = _require_adjoint_pair(
            left_commutator,
            right_commutator,
            ordered,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        orbital_gap = _orbital_gap(key, core_energy, virtual_energy)
        raw_ordered_dimension = int(np.count_nonzero(ordered))
        if normalized_groups is None:
            grouping_diagnostics = {
                "enabled": False,
                "raw_ordered_dimension": raw_ordered_dimension,
                "contracted_group_dimension": raw_ordered_dimension,
                "maximum_orbital_gap_spread": 0.0,
                "orbital_gap_tolerance_at_maximum": float(
                    strong_contraction_group_atol
                    + strong_contraction_group_rtol
                ),
            }
        else:
            grouped, orbital_gap, grouping_diagnostics = (
                _group_strong_contraction_arrays(
                    key,
                    (norm, right_commutator, left_commutator),
                    orbital_gap,
                    ordered,
                    normalized_groups,
                    eris,
                    atol=strong_contraction_group_atol,
                    rtol=strong_contraction_group_rtol,
                )
            )
            norm, right_commutator, left_commutator = grouped
            shape = norm.shape
            ordered = np.ones(shape, dtype=bool)
        orbital_gap = orbital_gap.astype(dtype, copy=False)

        # This reconciles two independently contracted representations of the
        # *same one-sided* scalar.  In exact arithmetic left.conj() == right,
        # so unlike the Hermitian half-sum below it does not remove a physical
        # one-sided imaginary residual.  Explicit symmetry-partner channels,
        # when requested, have already been summed above: the nonlinear SC
        # denominator must be formed only after that sum.
        si_right_commutator = 0.5 * (
            right_commutator + left_commutator.conj()
        )
        commutator = 0.5 * (right_commutator + left_commutator)

        selected_norm = norm[ordered]
        selected_norm = _require_real(
            selected_norm,
            root=root,
            subspace=key,
            quantity="norm",
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        if np.any(selected_norm < -norm_tol):
            minimum = float(np.min(selected_norm))
            _warn_numerical(
                f"root {root} subspace {key}: negative norm {minimum:.3e}"
            )

        nonzero_flat = selected_norm > norm_tol
        nonzero = np.zeros(shape, dtype=bool)
        nonzero[ordered] = nonzero_flat
        selected_commutator = _require_real(
            commutator[nonzero],
            root=root,
            subspace=key,
            quantity="Hermitian Dyall commutator",
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        zero_norm = ordered & ~nonzero
        zero_norm_diagnostics = _validate_zero_norm_commutator(
            commutator,
            zero_norm,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        right_zero_norm_diagnostics = _validate_zero_norm_commutator(
            right_commutator,
            zero_norm,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        left_zero_norm_diagnostics = _validate_zero_norm_commutator(
            left_commutator,
            zero_norm,
            root=root,
            subspace=key,
            atol=scalar_atol,
            rtol=scalar_rtol,
        )
        one_sided_gap = orbital_gap.copy()
        hermitianized_gap = orbital_gap.copy()
        if np.any(nonzero):
            retained_norm = selected_norm[nonzero_flat]
            one_sided_gap[nonzero] += (
                si_right_commutator[nonzero] / retained_norm
            )
            hermitianized_gap[nonzero] += (
                selected_commutator / retained_norm
            )
            si_real_gap, one_sided_diagnostics = (
                _audit_one_sided_si_denominator(
                    norm,
                    si_right_commutator,
                    one_sided_gap,
                    nonzero,
                    root=root,
                    subspace=key,
                    gap_atol=si_gap_imag_atol,
                    gap_rtol=si_gap_imag_rtol,
                    numerator_noise_allowance=si_numerator_noise_allowance,
                    energy_imag_l1_tol=si_energy_imag_l1_tol,
                    projection_shift_l1_tol=si_projection_shift_l1_tol,
                    denominator_tol=denominator_tol,
                    enforce=denominator_mode == "strict_si",
                )
            )
            if denominator_mode == "strict_si":
                real_gap = si_real_gap
                selected_gap = one_sided_gap.copy()
            else:
                real_gap = _require_real(
                    hermitianized_gap[nonzero],
                    root=root,
                    subspace=key,
                    quantity="Hermitianized Dyall denominator",
                    atol=scalar_atol,
                    rtol=scalar_rtol,
                )
                selected_gap = hermitianized_gap.copy()
            selected_gap[nonzero] = real_gap
            if np.any(real_gap <= denominator_tol):
                minimum = float(np.min(real_gap))
                raise FloatingPointError(
                    f"root {root} subspace {key}: non-positive or near-zero "
                    f"Dyall denominator {minimum:.3e}"
                )
            contribution = -np.sum(selected_norm[nonzero_flat] / real_gap)
            gap_min = float(np.min(real_gap))
            gap_max = float(np.max(real_gap))
        else:
            contribution = 0.0
            gap_min = np.nan
            gap_max = np.nan
            selected_gap = (
                one_sided_gap
                if denominator_mode == "strict_si"
                else hermitianized_gap
            )
            _si_real_gap, one_sided_diagnostics = (
                _audit_one_sided_si_denominator(
                    norm,
                    si_right_commutator,
                    one_sided_gap,
                    nonzero,
                    root=root,
                    subspace=key,
                    gap_atol=si_gap_imag_atol,
                    gap_rtol=si_gap_imag_rtol,
                    numerator_noise_allowance=si_numerator_noise_allowance,
                    energy_imag_l1_tol=si_energy_imag_l1_tol,
                    projection_shift_l1_tol=si_projection_shift_l1_tol,
                    denominator_tol=denominator_tol,
                    enforce=denominator_mode == "strict_si",
                )
            )

        class_diagnostics = {
            **branch_diagnostics,
            "contraction_backend": contraction_backend,
            "denominator_mode": denominator_mode,
            "selected_denominator_source": (
                "reconciled_right_si"
                if denominator_mode == "strict_si"
                else "hermitian_half_sum"
            ),
            "norm": _scalar_reality_diagnostics(
                norm, ordered, atol=scalar_atol, rtol=scalar_rtol
            ),
            "hermitian_commutator": _scalar_reality_diagnostics(
                commutator, ordered, atol=scalar_atol, rtol=scalar_rtol
            ),
            "one_sided_denominator": one_sided_diagnostics,
            "hermitianized_denominator": _scalar_reality_diagnostics(
                hermitianized_gap,
                nonzero,
                atol=scalar_atol,
                rtol=scalar_rtol,
            ),
            "zero_norm_hermitian_commutator": zero_norm_diagnostics,
            "zero_norm_right_commutator": right_zero_norm_diagnostics,
            "zero_norm_left_commutator": left_zero_norm_diagnostics,
            "strong_contraction_grouping": grouping_diagnostics,
            "minimum_retained_norm": (
                float(np.min(selected_norm[nonzero_flat]))
                if np.any(nonzero_flat)
                else None
            ),
            "ordered_dimension": int(np.count_nonzero(ordered)),
            "raw_ordered_dimension": raw_ordered_dimension,
            "retained_dimension": int(np.count_nonzero(nonzero_flat)),
            "discarded_zero_norm_dimension": int(np.count_nonzero(zero_norm)),
        }
        realness_diagnostics[key] = class_diagnostics

        sub_eners[key] = float(contribution)
        sub_norms[key] = float(np.sum(np.maximum(selected_norm, 0.0)))
        sub_gaps[key] = (gap_min, gap_max)
        if return_arrays:
            arrays[key] = {
                "norm": norm,
                "commutator": commutator,
                "right_commutator": right_commutator,
                "left_commutator": left_commutator,
                "si_right_commutator": si_right_commutator,
                "selected_commutator": (
                    si_right_commutator
                    if denominator_mode == "strict_si"
                    else commutator
                ),
                "orbital_gap": _orbital_gap(
                    key, core_energy, virtual_energy
                ),
                "denominator": selected_gap,
                "one_sided_denominator": one_sided_gap,
                "hermitianized_denominator": hermitianized_gap,
                "ordered": ordered,
                "nonzero": nonzero,
            }
        timings[key] = time.perf_counter() - subspace_start

    root_imaginary_energy_l1 = float(
        sum(
            diagnostics["one_sided_denominator"]["imaginary_energy_l1"]
            for diagnostics in realness_diagnostics.values()
        )
    )
    root_projection_shift_l1 = float(
        sum(
            diagnostics["one_sided_denominator"]["real_projection_shift_l1"]
            for diagnostics in realness_diagnostics.values()
        )
    )
    root_energy_gate_passed = bool(
        root_imaginary_energy_l1 <= si_energy_imag_l1_tol
    )
    root_projection_gate_passed = bool(
        root_projection_shift_l1 <= si_projection_shift_l1_tol
    )
    root_strict_si_compatible = bool(
        root_energy_gate_passed
        and root_projection_gate_passed
        and all(
            diagnostics["one_sided_denominator"]["strict_si_compatible"]
            for diagnostics in realness_diagnostics.values()
        )
    )
    root_audit = {
        "strict_si_compatible": root_strict_si_compatible,
        "imaginary_energy_l1": root_imaginary_energy_l1,
        "imaginary_energy_l1_tolerance": float(si_energy_imag_l1_tol),
        "imaginary_energy_l1_gate_passed": root_energy_gate_passed,
        "real_projection_shift_l1": root_projection_shift_l1,
        "real_projection_shift_l1_tolerance": float(
            si_projection_shift_l1_tol
        ),
        "real_projection_shift_l1_gate_passed": root_projection_gate_passed,
    }
    for diagnostics in realness_diagnostics.values():
        diagnostics["root_one_sided_si_audit"] = dict(root_audit)
    if denominator_mode == "strict_si" and not root_strict_si_compatible:
        _warn_numerical(
            f"root {root}: aggregate one-sided SI denominator audit failed; "
            f"Im(E) L1={root_imaginary_energy_l1:.3e}, "
            f"projection shift L1={root_projection_shift_l1:.3e}"
        )

    result = (sub_eners, sub_norms, sub_gaps)
    if return_arrays:
        result += (arrays,)
    if return_timings:
        result += (timings,)
    if return_diagnostics:
        result += (realness_diagnostics,)
    return result


