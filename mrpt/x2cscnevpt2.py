def _require_adjoint_pair(
    left,
    right,
    mask,
    *,
    root,
    subspace,
    atol,
    rtol,
):
    """Verify independently generated scalar branches are adjoints."""

    left = np.asarray(left)
    right = np.asarray(right)
    mask = np.asarray(mask, dtype=bool)
    if left.shape != right.shape or left.shape != mask.shape:
        raise ValueError("adjoint-branch arrays or mask have different shapes")
    selected_left = left[mask]
    selected_right = right[mask]
    if not np.all(np.isfinite(selected_left)) or not np.all(
        np.isfinite(selected_right)
    ):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: Dyall commutator branch "
            "contains non-finite values"
        )
    if not selected_left.size:
        return {
            "maximum_adjoint_error": 0.0,
            "maximum_adjoint_error_index": [],
            "reality_limit_at_maximum_error": float(atol + rtol),
            "adjoint_gate_passed": True,
        }

    error = np.abs(selected_left - selected_right.conj())
    limit = atol + rtol * np.maximum(
        1.0, np.maximum(np.abs(selected_left), np.abs(selected_right))
    )
    local_index = int(np.argmax(error))
    selected_flat = np.flatnonzero(mask)
    full_index = np.unravel_index(
        int(selected_flat[local_index]), left.shape
    )
    gate_passed = bool(error[local_index] <= limit[local_index])
    if not gate_passed:
        _warn_numerical(
            f"root {root} subspace {subspace}: independently generated "
            "Dyall commutator branches are not adjoints; maximum error = "
            f"{float(error[local_index]):.3e} at {full_index}"
        )
    return {
        "maximum_adjoint_error": float(error[local_index]),
        "maximum_adjoint_error_index": [int(index) for index in full_index],
        "reality_limit_at_maximum_error": float(limit[local_index]),
        "adjoint_gate_passed": gate_passed,
    }


def _scalar_reality_diagnostics(values, mask, *, atol, rtol):
    """Return the largest imaginary residual of a selected scalar array."""

    values = np.asarray(values)
    mask = np.asarray(mask, dtype=bool)
    selected = values[mask]
    if not selected.size:
        return {
            "maximum_imaginary_part": 0.0,
            "maximum_imaginary_index": [],
            "reality_limit_at_maximum": float(atol + rtol),
            "real_part_at_maximum": 0.0,
            "maximum_imaginary_to_limit_ratio": 0.0,
            "maximum_ratio_index": [],
            "gate_passed": True,
        }
    magnitude = np.abs(selected.imag)
    limits = atol + rtol * np.maximum(1.0, np.abs(selected.real))
    local_index = int(np.argmax(magnitude))
    selected_flat = np.flatnonzero(mask)
    full_index = np.unravel_index(
        int(selected_flat[local_index]), values.shape
    )
    ratio = np.divide(
        magnitude,
        limits,
        out=np.full_like(magnitude, np.inf, dtype=float),
        where=limits > 0.0,
    )
    ratio_index = int(np.argmax(ratio))
    ratio_full_index = np.unravel_index(
        int(selected_flat[ratio_index]), values.shape
    )
    return {
        "maximum_imaginary_part": float(magnitude[local_index]),
        "maximum_imaginary_index": [int(index) for index in full_index],
        "reality_limit_at_maximum": float(limits[local_index]),
        "real_part_at_maximum": float(selected[local_index].real),
        "maximum_imaginary_to_limit_ratio": float(ratio[ratio_index]),
        "maximum_ratio_index": [int(index) for index in ratio_full_index],
        "gate_passed": bool(np.all(magnitude <= limits)),
    }


def _audit_one_sided_si_denominator(
    norm,
    right_commutator,
    one_sided_gap,
    mask,
    *,
    root,
    subspace,
    gap_atol,
    gap_rtol,
    numerator_noise_allowance,
    energy_imag_l1_tol,
    projection_shift_l1_tol,
    denominator_tol,
    enforce,
):
    """Audit the literal SI denominator with a bounded near-null exception.

    Dividing a roundoff-sized imaginary numerator by a nearly null perturber
    norm can make the raw gap look complex even for an exact eigenvector.  A
    direct gap-gate failure is therefore accepted only when the numerator is
    within an explicit absolute noise allowance *and* both the imaginary
    energy and real-projection shift have small cancellation-free L1 bounds.
    """

    norm = np.asarray(norm)
    right_commutator = np.asarray(right_commutator)
    one_sided_gap = np.asarray(one_sided_gap)
    mask = np.asarray(mask, dtype=bool)
    if not (
        norm.shape
        == right_commutator.shape
        == one_sided_gap.shape
        == mask.shape
    ):
        raise ValueError("one-sided SI audit arrays or mask have different shapes")

    tolerances = {
        "gap_atol": float(gap_atol),
        "gap_rtol": float(gap_rtol),
        "numerator_noise_allowance": float(numerator_noise_allowance),
        "energy_imag_l1_tol": float(energy_imag_l1_tol),
        "projection_shift_l1_tol": float(projection_shift_l1_tol),
    }
    if any(
        not np.isfinite(value) or value < 0.0
        for value in tolerances.values()
    ):
        raise ValueError("strict-SI audit tolerances must be finite and non-negative")

    selected_norm = np.asarray(norm[mask].real, dtype=float)
    selected_numerator = right_commutator[mask]
    selected_gap = one_sided_gap[mask]
    selected_flat = np.flatnonzero(mask)
    if not selected_norm.size:
        diagnostics = {
            **_scalar_reality_diagnostics(
                one_sided_gap,
                mask,
                atol=tolerances["gap_atol"],
                rtol=tolerances["gap_rtol"],
            ),
            "strict_si_compatible": True,
            "direct_gap_gate_passed": True,
            "raw_numerator_gate_passed": True,
            "positive_denominator_gate_passed": True,
            "roundoff_limited_near_null_count": 0,
            "roundoff_limited_near_null_indices": [],
            "maximum_numerator_imaginary_part": 0.0,
            "maximum_numerator_imaginary_index": [],
            "maximum_numerator_imaginary_to_limit_ratio": 0.0,
            "maximum_numerator_ratio_index": [],
            "imaginary_energy_l1": 0.0,
            "imaginary_energy_l1_tolerance": tolerances[
                "energy_imag_l1_tol"
            ],
            "imaginary_energy_l1_gate_passed": True,
            "real_projection_shift_l1": 0.0,
            "real_projection_shift_l1_tolerance": tolerances[
                "projection_shift_l1_tol"
            ],
            "real_projection_shift_l1_gate_passed": True,
            "numerator_noise_allowance": tolerances[
                "numerator_noise_allowance"
            ],
            "numerical_policy": "explicit-calibrated-numerator-allowance",
        }
        return selected_norm, diagnostics

    if (
        not np.all(np.isfinite(selected_norm))
        or not np.all(np.isfinite(selected_numerator))
        or not np.all(np.isfinite(selected_gap))
    ):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: one-sided SI audit contains "
            "non-finite inputs"
        )

    gap_imag = np.abs(selected_gap.imag)
    gap_limit = tolerances["gap_atol"] + tolerances["gap_rtol"] * np.maximum(
        1.0, np.abs(selected_gap.real)
    )
    numerator_imag = np.abs(selected_numerator.imag)
    numerator_limit = (
        tolerances["numerator_noise_allowance"] + selected_norm * gap_limit
    )
    direct_gap_pass = gap_imag <= gap_limit
    numerator_pass = numerator_imag <= numerator_limit
    near_null = (
        ~direct_gap_pass
        & (
            selected_norm * gap_limit
            < tolerances["numerator_noise_allowance"]
        )
        & numerator_pass
    )
    gap_accepted = direct_gap_pass | near_null
    positive = selected_gap.real > denominator_tol

    with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
        complex_energy = -selected_norm / selected_gap
        projected_energy = -selected_norm / selected_gap.real
    finite_energies = np.all(np.isfinite(complex_energy)) and np.all(
        np.isfinite(projected_energy)
    )
    if not finite_energies:
        raise FloatingPointError(
            f"root {root} subspace {subspace}: one-sided SI energy audit "
            "produced non-finite values"
        )
    imaginary_energy_l1 = float(np.sum(np.abs(complex_energy.imag)))
    projection_shift_l1 = float(
        np.sum(np.abs(projected_energy - complex_energy.real))
    )
    energy_imag_pass = (
        imaginary_energy_l1 <= tolerances["energy_imag_l1_tol"]
    )
    projection_shift_pass = (
        projection_shift_l1 <= tolerances["projection_shift_l1_tol"]
    )
    strict_compatible = bool(
        np.all(gap_accepted)
        and np.all(numerator_pass)
        and np.all(positive)
        and finite_energies
        and energy_imag_pass
        and projection_shift_pass
    )

    def full_index(local_index):
        return [
            int(index)
            for index in np.unravel_index(
                int(selected_flat[int(local_index)]), mask.shape
            )
        ]

    numerator_ratio = np.divide(
        numerator_imag,
        numerator_limit,
        out=np.full_like(numerator_imag, np.inf, dtype=float),
        where=numerator_limit > 0.0,
    )
    numerator_max = int(np.argmax(numerator_imag))
    numerator_ratio_max = int(np.argmax(numerator_ratio))
    near_null_local = np.flatnonzero(near_null)
    diagnostics = {
        **_scalar_reality_diagnostics(
            one_sided_gap,
            mask,
            atol=tolerances["gap_atol"],
            rtol=tolerances["gap_rtol"],
        ),
        "strict_si_compatible": strict_compatible,
        "direct_gap_gate_passed": bool(np.all(direct_gap_pass)),
        "raw_numerator_gate_passed": bool(np.all(numerator_pass)),
        "positive_denominator_gate_passed": bool(np.all(positive)),
        "roundoff_limited_near_null_count": int(len(near_null_local)),
        "roundoff_limited_near_null_indices": [
            full_index(index) for index in near_null_local
        ],
        "maximum_numerator_imaginary_part": float(
            numerator_imag[numerator_max]
        ),
        "maximum_numerator_imaginary_index": full_index(numerator_max),
        "maximum_numerator_imaginary_to_limit_ratio": float(
            numerator_ratio[numerator_ratio_max]
        ),
        "maximum_numerator_ratio_index": full_index(numerator_ratio_max),
        "imaginary_energy_l1": imaginary_energy_l1,
        "imaginary_energy_l1_tolerance": tolerances["energy_imag_l1_tol"],
        "imaginary_energy_l1_gate_passed": bool(energy_imag_pass),
        "real_projection_shift_l1": projection_shift_l1,
        "real_projection_shift_l1_tolerance": tolerances[
            "projection_shift_l1_tol"
        ],
        "real_projection_shift_l1_gate_passed": bool(projection_shift_pass),
        "numerator_noise_allowance": tolerances[
            "numerator_noise_allowance"
        ],
        "numerical_policy": "explicit-calibrated-numerator-allowance",
    }
    if enforce and not strict_compatible:
        _warn_numerical(
            f"root {root} subspace {subspace}: one-sided SI denominator "
            "audit failed; "
            f"max |Im gap|={float(np.max(gap_imag)):.3e}, "
            f"max numerator ratio={float(np.max(numerator_ratio)):.3e}, "
            f"Im(E) L1={imaginary_energy_l1:.3e}, "
            f"projection shift L1={projection_shift_l1:.3e}"
        )
    return selected_gap.real, diagnostics


def _validate_zero_norm_commutator(
    values,
    mask,
    *,
    root,
    subspace,
    atol,
    rtol,
):
    """Gate and describe the Hermitian numerator of discarded perturbers."""

    values = np.asarray(values)
    mask = np.asarray(mask, dtype=bool)
    if values.shape != mask.shape:
        raise ValueError("zero-norm commutator array and mask have different shapes")
    selected = values[mask]
    if not np.all(np.isfinite(selected)):
        raise FloatingPointError(
            f"root {root} subspace {subspace}: zero-norm Dyall commutator "
            "contains non-finite values"
        )
    if not selected.size:
        return {
            "maximum_absolute_value": 0.0,
            "maximum_absolute_index": [],
            "acceptance_limit_at_maximum": float(atol + rtol),
            "gate_passed": True,
        }

    magnitude = np.abs(selected)
    limit = atol + rtol * np.maximum(1.0, np.abs(selected.real))
    local_index = int(np.argmax(magnitude))
    selected_flat = np.flatnonzero(mask)
    full_index = np.unravel_index(
        int(selected_flat[local_index]), values.shape
    )
    gate_passed = bool(magnitude[local_index] <= limit[local_index])
    if not gate_passed:
        _warn_numerical(
            f"root {root} subspace {subspace}: a zero-norm perturber has "
            f"nonzero Dyall commutator {float(magnitude[local_index]):.3e} "
            f"at {full_index}"
        )
    return {
        "maximum_absolute_value": float(magnitude[local_index]),
        "maximum_absolute_index": [int(index) for index in full_index],
        "acceptance_limit_at_maximum": float(limit[local_index]),
        "gate_passed": gate_passed,
    }


