class WickX2CSCNEVPT2(lib.StreamObject):
    """State-specific dense spinor SC-NEVPT2 generated with Block2 Wick."""

    def __init__(self, mc, frozen=0):
        if _has_frozen_orbitals(frozen) or _has_frozen_orbitals(
            getattr(mc, "frozen", None)
        ):
            raise NotImplementedError("nonzero frozen spinors are outside dense v1")
        self._mc = mc
        self._scf = mc._scf
        self.mol = self._scf.mol
        self.verbose = getattr(mc, "verbose", self.mol.verbose)
        self.stdout = getattr(mc, "stdout", self.mol.stdout)
        self.root = 0
        self.mo_coeff = getattr(mc, "mo_coeff", None)
        self.mo_energy = getattr(mc, "mo_energy", None)
        self.canonicalized = False
        self.eris = None
        self.eris_basis = None
        self.e_corr = None
        self.reference_energy = None
        self.sub_eners = {}
        self.sub_norms = {}
        self.sub_denominators = {}
        self.sub_realness_diagnostics = {}
        self.sub_times = {}
        self.rdm_diagnostics = None
        self.integral_symmetry_diagnostics = None
        for name, value in _SC_NUMERICAL_DEFAULTS:
            setattr(self, name, value)
        self.denominator_mode = "strict_si"
        self.contraction_backend = _DEFAULT_CONTRACTION_BACKEND
        self.strong_contraction_groups = None
        self.strict_si_compatible = None
        self.scalar_tolerance = None
        self.reference_residual_bound = None
        self.frozen = 0
        self._keys = set(self.__dict__)

    @property
    def e_tot(self):
        if self.e_corr is None:
            return None
        return np.asarray(self.reference_energy) + np.asarray(self.e_corr)

    def _semicanonicalize(self, mc, mo_coeff, dm1, root):
        if self.canonicalized:
            if self.mo_energy is None:
                self.mo_energy = getattr(mc, "mo_energy", None)
            if self.mo_energy is None:
                raise ValueError(
                    "canonicalized=True requires prepared spinor orbital energies"
                )
            energies = np.asarray(self.mo_energy)
            if energies.shape != (mo_coeff.shape[1],):
                raise ValueError("mo_energy has the wrong shape")
            if not np.all(np.isfinite(energies)):
                raise ValueError("mo_energy contains non-finite values")
            if np.iscomplexobj(energies) and _maximum_abs(energies.imag) > 1e-12:
                _warn_numerical(
                    "semicanonical orbital energies have imaginary components; "
                    "using their real parts"
                )
            return np.asarray(mo_coeff), np.asarray(energies.real, dtype=float)

        ci = _select_root_ci(
            getattr(mc, "ci", None),
            root,
            nroots=getattr(getattr(mc, "fcisolver", None), "nroots", 1),
        )
        rotated, _ci, energies = mc.canonicalize(
            mo_coeff,
            ci=ci,
            cas_natorb=False,
            casdm1=dm1,
            verbose=self.verbose,
        )
        rotated = np.asarray(rotated)
        ncore = int(mc.ncore)
        nocc = ncore + int(mc.ncas)
        active_change = _maximum_abs(
            rotated[:, ncore:nocc] - np.asarray(mo_coeff)[:, ncore:nocc]
        )
        if active_change > 1.0e-12:
            raise RuntimeError(
                "root-specific semicanonicalization changed active orbitals "
                f"by {active_change:.3e}; the MPS/RDM basis would be invalid"
            )
        return rotated, np.asarray(energies, dtype=float)

    def _prepare_sc_root(
        self,
        mc,
        *,
        mo_coeff,
        pdms,
        eris,
        eris_basis,
        root,
        denominator_mode,
        contraction_backend,
        strong_contraction_groups=None,
        return_arrays=False,
        compact_eris=False,
        retain_pdms123=False,
    ) -> _PreparedSCRoot:
        """Prepare one audited multipartitioning row without committing state.

        This is the single numerical path used by both the public
        state-specific kernel and the QD driver.  It deliberately calls
        the instance ``_semicanonicalize`` hook so injected and
        subclass-provided canonicalization policies remain valid.
        """

        reference_energy = _reference_energy(mc, root)
        solver = mc.fcisolver
        residual_bound = getattr(solver, "convergence_info", {}).get(
            "local_residual_bound", 0.0
        )
        residual_bound = float(residual_bound)
        if not np.isfinite(residual_bound) or residual_bound < 0.0:
            residual_bound = 0.0
        # The requested local eigensolver threshold is useful provenance, but
        # is not a measured contraction-error bound and therefore does not
        # relax either the strict-SI or Hermitianized scalar checks.
        scalar_tolerance = float(self.scalar_atol)

        pdm_start = time.perf_counter()
        if pdms is None:
            pdms = make_dm1234(mc.fcisolver, root=root)
        solver_nelecas = getattr(mc.fcisolver, "nelecas", None)
        if solver_nelecas is None:
            solver_nelecas = mc.nelecas
        pdms, rdm_diagnostics = validate_pdms(
            pdms,
            int(mc.ncas),
            _total_nelec(solver_nelecas),
            atol=self.rdm_atol,
            rtol=self.rdm_rtol,
            work_memory=self.rdm_work_memory,
        )
        retained_pdms123 = tuple(pdms[:3]) if retain_pdms123 else None
        pdm_time = time.perf_counter() - pdm_start

        integral_start = time.perf_counter()
        original_mo = np.asarray(mo_coeff)
        semicanonical_mo, orbital_energy = self._semicanonicalize(
            mc, original_mo, pdms[0], root
        )
        if eris is None:
            prepared_eris = _dense_eris_from_mc(
                mc,
                semicanonical_mo,
                roundoff_factor=self.integral_roundoff_factor,
            )
            integral_symmetry_diagnostics = getattr(
                prepared_eris, "symmetry_diagnostics", None
            )
            if compact_eris:
                prepared_eris = _compact_wick_eris(prepared_eris)
        else:
            if not isinstance(eris, spinor_helper._SpinorERIs):
                raise TypeError(
                    "eris must be a spinor_helper._SpinorERIs instance"
                )
            if (eris.ncore, eris.ncas, eris.nmo) != (
                int(mc.ncore),
                int(mc.ncas),
                semicanonical_mo.shape[1],
            ):
                raise ValueError("eris partition does not match the CASSCF object")
            prepared_eris = eris
            integral_symmetry_diagnostics = getattr(
                prepared_eris, "symmetry_diagnostics", None
            )
            if (
                eris_basis == "input_mo"
                and not np.array_equal(semicanonical_mo, original_mo)
            ):
                overlap = np.asarray(mc._scf.get_ovlp())
                rotation = original_mo.T.conj() @ overlap @ semicanonical_mo
                if compact_eris:
                    prepared_eris = _rotate_wick_eris(eris, rotation)
                else:
                    prepared_eris = _rotate_eris(eris, rotation)
            elif compact_eris:
                prepared_eris = _compact_wick_eris(eris)
        integral_time = time.perf_counter() - integral_start

        ncore = prepared_eris.ncore
        nocc = prepared_eris.nocc
        core_energy = orbital_energy[:ncore]
        virtual_energy = orbital_energy[nocc:]
        evaluated = _evaluate_wick_subspaces(
            prepared_eris,
            pdms,
            core_energy,
            virtual_energy,
            root=root,
            scalar_atol=scalar_tolerance,
            scalar_rtol=self.scalar_rtol,
            norm_tol=self.norm_tol,
            denominator_tol=self.denominator_tol,
            denominator_mode=denominator_mode,
            si_gap_imag_atol=self.si_gap_imag_atol,
            si_gap_imag_rtol=self.si_gap_imag_rtol,
            si_numerator_noise_allowance=self.si_numerator_noise_allowance,
            si_energy_imag_l1_tol=self.si_energy_imag_l1_tol,
            si_projection_shift_l1_tol=self.si_projection_shift_l1_tol,
            contraction_backend=contraction_backend,
            strong_contraction_groups=strong_contraction_groups,
            strong_contraction_group_atol=(
                self.strong_contraction_group_atol
            ),
            strong_contraction_group_rtol=(
                self.strong_contraction_group_rtol
            ),
            return_arrays=return_arrays,
            return_timings=True,
            return_diagnostics=True,
        )
        if return_arrays:
            (
                sub_eners,
                sub_norms,
                sub_gaps,
                subspace_arrays,
                subspace_times,
                realness_diagnostics,
            ) = evaluated
        else:
            (
                sub_eners,
                sub_norms,
                sub_gaps,
                subspace_times,
                realness_diagnostics,
            ) = evaluated
            subspace_arrays = None
        strict_si_compatible = all(
            diagnostics["root_one_sided_si_audit"]["strict_si_compatible"]
            for diagnostics in realness_diagnostics.values()
        )
        return _PreparedSCRoot(
            root=root,
            reference_energy=reference_energy,
            reference_residual_bound=residual_bound,
            scalar_tolerance=scalar_tolerance,
            mo_coeff=semicanonical_mo,
            orbital_energy=orbital_energy,
            eris=prepared_eris,
            eris_basis="semicanonical",
            core_energy=core_energy,
            virtual_energy=virtual_energy,
            pdms123=retained_pdms123,
            subspace_arrays=subspace_arrays,
            subspace_energies=sub_eners,
            subspace_norms=sub_norms,
            subspace_gaps=sub_gaps,
            subspace_diagnostics=realness_diagnostics,
            subspace_times=subspace_times,
            rdm_diagnostics=rdm_diagnostics,
            integral_symmetry_diagnostics=integral_symmetry_diagnostics,
            pdm_time=pdm_time,
            integral_time=integral_time,
            strict_si_compatible=strict_si_compatible,
            e_corr=float(sum(sub_eners.values())),
        )

    def kernel(
        self,
        mc=None,
        mo_coeff=None,
        pdms=None,
        eris=None,
        eris_basis="input_mo",
        denominator_mode=None,
        root=None,
        contraction_backend=None,
        strong_contraction_groups=None,
        compact_eris=False,
    ):
        """Compute one root-specific SC-NEVPT2 correction.

        ``contraction_backend`` selects ``"pytblis"`` (the default) or the
        NumPy reference implementation for the Block2-generated contractions.
        ``strong_contraction_groups`` is an optional integer label for every
        semicanonical spinor MO.  Equal core or virtual labels are summed
        before forming a denominator; this is required to reproduce a
        spin-free SC contraction from explicit alpha/beta spinors.  Because
        labels describe the final MO columns, this option requires
        ``canonicalized=True``.
        With a dense input-basis ``eris``, ``compact_eris=True`` rotates and
        retains only the blocks used by Wick; the default preserves the
        historical full-ERI result object.
        """

        if mc is None:
            mc = self._mc
        if _has_frozen_orbitals(getattr(mc, "frozen", None)):
            raise NotImplementedError("nonzero frozen spinors are outside dense v1")
        eris_basis = _normalize_eris_basis(eris_basis)
        if denominator_mode is None:
            denominator_mode = self.denominator_mode
        denominator_mode = _normalize_denominator_mode(denominator_mode)
        self.denominator_mode = denominator_mode
        if contraction_backend is None:
            contraction_backend = self.contraction_backend
        contraction_backend = _normalize_contraction_backend(
            contraction_backend
        )
        self.contraction_backend = contraction_backend
        if strong_contraction_groups is None:
            strong_contraction_groups = self.strong_contraction_groups
        else:
            strong_contraction_groups = np.asarray(
                strong_contraction_groups
            ).copy()
            self.strong_contraction_groups = strong_contraction_groups
        if strong_contraction_groups is not None and not self.canonicalized:
            raise ValueError(
                "strong_contraction_groups describes semicanonical MO columns; "
                "set canonicalized=True and supply matching mo_energy"
            )
        if root is None:
            root = self.root
        root = int(root)
        if root < 0:
            raise IndexError("root must be non-negative")
        self.root = root
        if mo_coeff is None:
            mo_coeff = mc.mo_coeff
        mo_coeff = np.asarray(mo_coeff)
        row = self._prepare_sc_root(
            mc,
            mo_coeff=mo_coeff,
            pdms=pdms,
            eris=eris,
            eris_basis=eris_basis,
            root=root,
            denominator_mode=denominator_mode,
            contraction_backend=contraction_backend,
            strong_contraction_groups=strong_contraction_groups,
            return_arrays=False,
            compact_eris=bool(compact_eris),
        )
        self.reference_energy = row.reference_energy
        self.reference_residual_bound = row.reference_residual_bound
        self.scalar_tolerance = row.scalar_tolerance
        self.rdm_diagnostics = row.rdm_diagnostics
        self.mo_coeff = row.mo_coeff
        self.mo_energy = row.orbital_energy
        self.eris = row.eris
        self.eris_basis = row.eris_basis
        self.integral_symmetry_diagnostics = row.integral_symmetry_diagnostics
        self.strict_si_compatible = row.strict_si_compatible

        sub_eners = row.subspace_energies
        sub_norms = row.subspace_norms
        sub_gaps = row.subspace_gaps
        subspace_times = row.subspace_times
        realness_diagnostics = row.subspace_diagnostics
        self.sub_times = {"pdms": row.pdm_time, "eris": row.integral_time}
        self.sub_eners = {}
        self.sub_norms = {}
        self.sub_denominators = {}
        self.sub_realness_diagnostics = {}
        if denominator_mode == "hermitianized" and not self.strict_si_compatible:
            failed = ", ".join(
                key
                for key, diagnostics in realness_diagnostics.items()
                if not diagnostics["one_sided_denominator"][
                    "strict_si_compatible"
                ]
            )
            if not failed:
                failed = "<aggregate L1 gate>"
            logger.warn(
                self,
                "root %d uses denominator_mode=hermitianized; the one-sided "
                "SI audit failed for classes: %s",
                root,
                failed,
            )
        for key in SUBSPACE_ORDER:
            self.sub_eners[key] = sub_eners[key]
            self.sub_norms[key] = sub_norms[key]
            self.sub_denominators[key] = sub_gaps[key]
            self.sub_realness_diagnostics[key] = realness_diagnostics[key]
            self.sub_times[key] = subspace_times[key]
            logger.note(
                self,
                "root %d E(%s-%4s) = %20.14f  norm = %.10g  gap = [%s, %s]",
                root,
                self.__class__.__name__,
                key,
                sub_eners[key],
                sub_norms[key],
                "nan" if np.isnan(sub_gaps[key][0]) else f"{sub_gaps[key][0]:.8g}",
                "nan" if np.isnan(sub_gaps[key][1]) else f"{sub_gaps[key][1]:.8g}",
            )
        self.e_corr = float(sum(self.sub_eners.values()))
        logger.note(
            self,
            "root %d E(reference) = %.16g  E_corr = %.16g  E(total) = %.16g",
            root,
            self.reference_energy,
            self.e_corr,
            self.e_tot,
        )
        logger.info(
            self,
            "root %d contraction_backend=%s denominator_mode=%s "
            "strict_si_compatible=%s; "
            "physical-scalar realness tolerance = %.3e "
            "(configured %.3e; DMRG local threshold bound %.3e is diagnostic only)",
            root,
            contraction_backend,
            denominator_mode,
            self.strict_si_compatible,
            self.scalar_tolerance,
            self.scalar_atol,
            self.reference_residual_bound,
        )
        logger.note(
            self,
            "root %d timings: %s",
            root,
            " | ".join(f"{key}={value:.2f}s" for key, value in self.sub_times.items()),
        )
        return self.e_corr


