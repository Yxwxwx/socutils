r"""General-complex-spinor X2C fully internally contracted MR-REPT2.

This module implements the state-specific, full-class-matrix second-order
retaining-the-excitation-degree perturbation theory of Fink [Chem. Phys.
Lett. 428, 461 (2006); Chem. Phys. 356, 39 (2009)].  It is structurally based
on the GPL-3.0-or-later Block2 ``pyblock2.icmr.icmrrept2_full`` driver
(Copyright 2020-2021 Huanchen Zhai), while replacing its spin-free and real
orbital assumptions by explicit fermionic creation/destruction operators,
raw spin-orbital one- through four-particle RDMs, and Hermitian complex
linear algebra.

Fink's zeroth-order Hamiltonian is generated by retaining every term of the
bare physical Hamiltonian that conserves the electron number separately in
the inactive, active, and external orbital spaces.  No orbital energies,
Dyall Hamiltonian, semicanonicalization, strong contraction, or level shift
is used.  For each of the eight internally contracted excitation classes,
all core/external free-index tuples are coupled in one full matrix.

The installed Block2 ``full`` implementation uses ``trunc_thrds`` as an
absolute *overlap-metric* eigenvalue cutoff and delegates singular response
directions to ``numpy.linalg.lstsq``.  This implementation preserves the
former meaning and exposes a separate ``denominator_atol`` for the latter;
discarding a near-zero response mode with material source weight is a hard
error rather than a silent regularization.

Official-source map (``pyblock2.icmr.icmrrept2_full``): its nine contracted
operator families ``ijrs/rsi/ijr/rs/ij/ir1/ir2/r/i`` are the eight public
classes here (the two semi-internal ``ir`` families share one full matrix);
``norm_eqs`` gives the overlap metric, ``ener_eqs`` gives the shifted Fink-H0
matrix, and ``rhhk_eqs`` gives the Hamiltonian source.  The official nested
index assembly couples every active and core/external free direction before
solving.  Its ``trunc_thrds`` filters overlap eigenvalues, and its final class
contribution is the source--first-order-wavefunction contraction.  Here those
objects are regenerated with ordinary complex C/D algebra, and H0 is generated
from the population-balance rule instead of a hand-maintained term list.
"""

