@dataclass(frozen=True)
class _ICComponent:
    """One one-/two-body operator family in an IC excitation class."""

    name: str
    expression: str
    ket_active: tuple[str, ...]
    bra_active: tuple[str, ...]
    active_pairs: tuple[tuple[int, int], ...] = ()

    def __post_init__(self):
        if len(self.ket_active) != len(self.bra_active):
            raise ValueError("ket and bra active-index ranks must agree")
        if len(set(self.ket_active)) != len(self.ket_active):
            raise ValueError("ket active labels must be distinct")
        if len(set(self.bra_active)) != len(self.bra_active):
            raise ValueError("bra active labels must be distinct")
        for left, right in self.active_pairs:
            if not (0 <= left < right < len(self.ket_active)):
                raise ValueError("invalid active-pair restriction")


