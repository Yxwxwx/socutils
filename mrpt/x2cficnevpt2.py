r"""Dense general-complex-spinor fully internally contracted NEVPT2.

This module implements the single-state, second-order, internally contracted
NEVPT2 equations for the same no-pair X2C spinor Hamiltonian used by
:mod:`x2cscnevpt2`,

.. math::

   H = \sum_{pq} h_{pq} C_p D_q
       + \frac12 \sum_{pqrs} w_{pqrs} C_p C_q D_s D_r,

with unantisymmetrized spinor integrals

.. math::

   w_{pqrs} = \mathrm{eri}_{prqs},\qquad
   \mathrm{eri}_{pqrs}=(pq|rs).

Every index labels one complex spinor. There is no spin summation, spatial
``E1/E2`` operator, Kramers compression, density fitting, Cholesky
factorization, QD coupling, or compressed-RDM approximation.

Terminology
-----------
The approximation implemented here is the internally contracted/partially
contracted variant introduced by Angeli, Cimiraglia, and Malrieu,
J. Chem. Phys. 117, 9138 (2002). Modern program documentation often calls the
same wave-function ansatz *fully internally contracted* (FIC) NEVPT2. The
public class therefore uses the ``FIC`` name, while ``IC`` and ``PC`` aliases
are provided for interoperability.

Operator definition
-------------------
For a fixed set ``eta`` of inactive holes and external particles, let
``O[eta,mu]`` denote all one- and two-body excitation operators that reach the
corresponding first-order interacting subspace. The contracted basis is

.. math::

   |\Phi_{\eta\mu}\rangle = O_{\eta\mu}|\Psi_0\rangle.

The projected source uses the shared, independently audited NEVPT2 definition,

.. math::

   |B_\eta\rangle = P_\eta H|\Psi_0\rangle.

Block2 Wick algebra generates, directly in the raw SGF 1--4 RDM convention,

.. math::

   S^\eta_{\mu\nu}
     &= \langle\Psi_0|O_{\eta\mu}^\dagger O_{\eta\nu}|\Psi_0\rangle,\\
   K^\eta_{\mu\nu}
     &= \langle\Psi_0|O_{\eta\mu}^\dagger
        [H_{\rm act}^{D},O_{\eta\nu}]|\Psi_0\rangle,\\
   b^\eta_\mu
     &= \langle\Psi_0|O_{\eta\mu}^\dagger B_\eta|\Psi_0\rangle.

The complete Dyall matrix in that block is

.. math::

   A^\eta = K^\eta + \Delta_\eta^{\rm orb} S^\eta
           = \langle\Phi_\eta|(H_D-E_0)|\Phi_\eta\rangle.

After canonical orthogonalization of the nonorthogonal contracted basis, the
linear problem is solved in its positive, non-null metric subspace and the
energy is

.. math::

   E^{(2)}_\eta = - (b^\eta)^\dagger (A^\eta)^+ b^\eta.

The explicit one-body components in the ``ir``, ``r``, and ``i`` spaces make
the basis complete even in limiting active-electron occupations. They are
usually linearly dependent on part of the two-body contracted basis; metric
canonicalization removes that redundancy without changing the physical span.

The implementation constructs the overlap, right and left Dyall-commutator
matrices and audits their exact Hermitian/eigenstate relations before
projecting finite numerical noise onto the required Hermitian matrices.
Non-finite values, a physically negative metric, a source outside the retained
metric range, or a non-positive Dyall eigenvalue remain hard errors.
"""

