_FREE_PAIRS = _utils._PAIR_RESTRICTIONS


@dataclass(frozen=True)
class _FICEquationBundle:
    rhs_code: dict[tuple[str, str], str]
    metric_code: dict[tuple[str, str, str], str]
    right_code: dict[tuple[str, str, str], str]
    left_code: dict[tuple[str, str, str], str]
    rhs_text: dict[tuple[str, str], str]
    metric_text: dict[tuple[str, str, str], str]
    right_text: dict[tuple[str, str, str], str]
    left_text: dict[tuple[str, str, str], str]


def _replace_active_labels(expression: str, mapping: dict[str, str]) -> str:
    """Replace only bracketed one-index operator labels."""

    result = expression
    for source, target in mapping.items():
        result = result.replace(f"[{source}]", f"[{target}]")
    return result


def _target(parse_tensor, name: str, labels: tuple[str, ...]):
    return parse_tensor(f"{name}[{''.join(labels)}]")


@lru_cache(maxsize=1)
def _compile_fic_equations() -> _FICEquationBundle:
    """Generate all FIC RHS, metric, and Dyall-matrix contractions."""

    types = _utils._block2_wick_types()
    parse, parse_tensor = _utils._wick_parsers(types)

    h_dyall_active = parse("SUM <ab> h[ab] C[a] D[b]")
    h_dyall_active += parse(
        "0.5 SUM <abcd> w[abcd] C[a] C[b] D[d] D[c]"
    )

    rhs_code = {}
    metric_code = {}
    right_code = {}
    left_code = {}
    rhs_text = {}
    metric_text = {}
    right_text = {}
    left_text = {}

    for key in SUBSPACE_ORDER:
        source = parse(_utils._PERTURBER_EXPRESSIONS[key])
        components = _IC_COMPONENTS[key]
        ket_expressions = {
            component.name: parse(component.expression)
            for component in components
        }
        bra_expressions = {}
        for component in components:
            mapped = _replace_active_labels(
                component.expression,
                dict(zip(component.ket_active, component.bra_active)),
            )
            bra_expressions[component.name] = parse(mapped).conjugate()

        free_labels = tuple(key)
        for bra_component in components:
            bra = bra_expressions[bra_component.name]
            rhs = _utils._lower_active_operators(
                _utils._vacuum_reduce(bra * source), types
            )
            labels = free_labels + bra_component.bra_active
            rhs_code[(key, bra_component.name)] = rhs.to_einsum(
                _target(parse_tensor, "rhs", labels)
            )
            rhs_text[(key, bra_component.name)] = repr(rhs)

            for ket_component in components:
                ket = ket_expressions[ket_component.name]
                pair = (key, bra_component.name, ket_component.name)
                labels = (
                    free_labels
                    + bra_component.bra_active
                    + ket_component.ket_active
                )

                metric = _utils._lower_active_operators(
                    _utils._vacuum_reduce(bra * ket), types
                )

                # [one-/two-body H_D, one-/two-body O] is connected and
                # contains at most three creation and three annihilation
                # operators. This is the same max_unctr policy used by SC.
                connected_right = (
                    (h_dyall_active ^ ket).expand(6).simplify()
                )
                right = _utils._lower_active_operators(
                    _utils._vacuum_reduce(bra * connected_right), types
                )
                connected_left = (
                    (bra ^ h_dyall_active).expand(6).simplify()
                )
                left = _utils._lower_active_operators(
                    _utils._vacuum_reduce(connected_left * ket), types
                )

                metric_code[pair] = metric.to_einsum(
                    _target(parse_tensor, "metric", labels)
                )
                right_code[pair] = right.to_einsum(
                    _target(parse_tensor, "right", labels)
                )
                left_code[pair] = left.to_einsum(
                    _target(parse_tensor, "left", labels)
                )
                metric_text[pair] = repr(metric)
                right_text[pair] = repr(right)
                left_text[pair] = repr(left)

    return _FICEquationBundle(
        rhs_code=rhs_code,
        metric_code=metric_code,
        right_code=right_code,
        left_code=left_code,
        rhs_text=rhs_text,
        metric_text=metric_text,
        right_text=right_text,
        left_text=left_text,
    )


def dump_fic_wick_equations(filename: str | None = None) -> str:
    """Return, and optionally write, every generated FIC Wick equation."""

    equations = _compile_fic_equations()
    sections = []
    for key in SUBSPACE_ORDER:
        sections.append(f"[{key}] source\n{_utils._PERTURBER_EXPRESSIONS[key]}")
        for component in _IC_COMPONENTS[key]:
            sections.extend(
                (
                    f"[{key}/{component.name}] basis\n{component.expression}",
                    f"[{key}/{component.name}] RHS expression\n"
                    f"{equations.rhs_text[(key, component.name)]}",
                    f"[{key}/{component.name}] RHS einsum\n"
                    f"{equations.rhs_code[(key, component.name)]}",
                )
            )
        for bra_component in _IC_COMPONENTS[key]:
            for ket_component in _IC_COMPONENTS[key]:
                pair = (key, bra_component.name, ket_component.name)
                title = f"{key}/{bra_component.name},{ket_component.name}"
                sections.extend(
                    (
                        f"[{title}] metric expression\n"
                        f"{equations.metric_text[pair]}",
                        f"[{title}] metric einsum\n"
                        f"{equations.metric_code[pair]}",
                        f"[{title}] right Dyall expression\n"
                        f"{equations.right_text[pair]}",
                        f"[{title}] right Dyall einsum\n"
                        f"{equations.right_code[pair]}",
                        f"[{title}] left Dyall expression\n"
                        f"{equations.left_text[pair]}",
                        f"[{title}] left Dyall einsum\n"
                        f"{equations.left_code[pair]}",
                    )
                )
    text = "\n\n".join(sections) + "\n"
    if filename is not None:
        with open(filename, "w", encoding="utf-8") as handle:
            handle.write(text)
    return text


